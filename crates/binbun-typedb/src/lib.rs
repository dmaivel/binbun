//! A type library: declarations of the functions and types of known
//! libraries, keyed by library and name, each fact with where it comes
//! from.
//!
//! Analyses ask it about code they cannot see, such as imports; they never
//! hold names themselves. Which function a piece of code *is* (an import's
//! name, a signature match on statically linked code) is decided elsewhere;
//! this library only says what is known about it.
//!
//! The facts are whether a function never returns, whether it never
//! throws, its prototype, with
//! the types the prototype refers to, and the format string it takes
//! (`printf`'s). They come from type databases
//! generated from declarations ([`database`], read from [`jsonl`] files by
//! [`TypeLibrary::add`]): C headers, Windows metadata, syzkaller's syscall
//! descriptions. Below them are hand-written [`overrides`], each fact with
//! the standard, documentation or source it comes from
//! ([`Origin::Override`]). A function is never said not to return because
//! of its name or its `void` return type, nor said not to throw because
//! of its name; only a declaration or a cited override says so.
//!
//! [`TypeLibrary::for_target`] gives the built-in facts and the databases
//! binbun embeds (Linux x86-64 and AArch64 glibc and C++ runtime ABI, Linux
//! x86-64 and AArch64 syscalls, the Windows x86-64 C runtime, native API
//! and Win32, what Windows x86-64 kernel-mode code imports, macOS x86-64
//! and arm64's C library and C++ runtime ABI from the SDK; compressed, each
//! decompressed when a binary of its target first needs it) with those
//! found in the database directory (plain or zstd-compressed, adding to or
//! replacing the embedded ones); [`TypeLibrary::for_mode`] those for
//! Windows kernel-mode code (drivers: the kernel's exports, without a
//! process's Win32 and native API).
//!
//! C declarations typed by a user (or laid over bytes) are read by [`c`]
//! into a table of these types, against a library's named types.

