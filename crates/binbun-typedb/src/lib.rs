/// Where a fact comes from, weakest first.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Origin {
    /// A hand-written override ([`overrides`]), with the reason it holds
    /// (a standard, documentation, the library's source), for a fact no
    /// embedded declaration states for every target. Matched by name (and
    /// library, if it gives one): a library could export an unrelated
    /// function of the same name. Below declarations, which say what the
    /// library at hand declares.
    Override,
    /// syzkaller's syscall descriptions, written by hand for fuzzing:
    /// semantic types (flag sets, resources), but integer widths
    /// approximated.
    Syzlang,
    /// Windows metadata, generated by Microsoft from the SDK headers.
    Winmd,
    /// A C header, as the compiler reads it.
    Header,
}

/// A fact and its origin.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct Fact<T> {
    /// The fact.
    pub value: T,
    /// Where it comes from.
    pub origin: Origin,
}

/// What is declared about one function.
#[derive(Clone, Debug, Default, PartialEq, Eq, Hash)]
pub struct Declaration {
    /// Whether it never returns to its caller.
    pub no_return: Option<Fact<bool>>,
    /// Whether it never throws an exception (C++ `throw()` or `noexcept`,
    /// `__attribute__((nothrow))`): an exception never unwinds out of a
    /// call to it.
    pub no_throw: Option<Fact<bool>>,
    /// Its prototype, with types in the [`TypeLibrary`] that holds it.
    pub prototype: Option<Fact<Signature<TypeId>>>,
    /// The format string it takes, where a declaration states one.
    pub format: Option<Fact<Format>>,
    /// The parameters (counted from 1) whose format string its result is,
    /// translated, where a declaration states them (`format_arg`).
    pub format_arg: Option<Fact<Vec<u32>>>,
    /// The parameters (counted from 1) whose value, or the product of
    /// whose two values, is the size in bytes of the object it returns,
    /// where a declaration states them (`alloc_size`).
    pub alloc_size: Option<Fact<Vec<u32>>>,
}

impl Declaration {
    /// Takes each fact of `other` that is stronger than this one's (or
    /// that this one lacks); of two facts of equal origin, keeps this one.
    fn merge(&mut self, other: Self) {
        fn stronger<T>(slot: &mut Option<Fact<T>>, fact: Option<Fact<T>>) {
            if let Some(fact) = fact
                && slot.as_ref().is_none_or(|old| fact.origin > old.origin)
            {
                *slot = Some(fact);
            }
        }
        stronger(&mut self.no_return, other.no_return);
        stronger(&mut self.no_throw, other.no_throw);
        stronger(&mut self.prototype, other.prototype);
        stronger(&mut self.format, other.format);
        stronger(&mut self.format_arg, other.format_arg);
        stronger(&mut self.alloc_size, other.alloc_size);
    }
}

/// A type in a [`TypeLibrary`]: its index in the library's type table.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct TypeId(u32);

impl TypeId {
    /// Its index in the type table.
    pub fn index(self) -> usize {
        self.0 as usize
    }
}

/// A type in a [`TypeLibrary`], referring to others by [`TypeId`].
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum Type {
    /// `void`.
    Void,
    /// `_Bool`.
    Bool,
    /// Plain `char`.
    Char {
        /// Whether `char` is signed on the target.
        signed: bool,
    },
    /// An integer.
    Int {
        /// Whether it is signed.
        signed: bool,
        /// Its size in bytes.
        size: u8,
    },
    /// A floating-point number.
    Float(FloatFormat),
    /// A pointer.
    Pointer(TypeId),
    /// An array.
    Array {
        /// The element type.
        element: TypeId,
        /// The number of elements (`None`: unbounded).
        count: Option<u64>,
    },
    /// A function type.
    Function(Signature<TypeId>),
    /// A structure or union.
    Record(Record<TypeId>),
    /// An enumeration or flag set.
    Enum(Enum),
    /// A typedef, a named atom over its target.
    Typedef(Typedef<TypeId>),
    /// A type named but not described.
    Opaque(Opaque),
}

impl Type {
    /// The key of a named type (a record, enumeration, typedef or opaque
    /// type) in its database: `struct stat`, `size_t`; `None` for the
    /// others.
    pub fn key(&self) -> Option<&str> {
        match self {
            Self::Record(record) => Some(&record.key),
            Self::Enum(definition) => Some(&definition.key),
            Self::Typedef(typedef) => Some(&typedef.key),
            Self::Opaque(opaque) => Some(&opaque.key),
            Self::Void
            | Self::Bool
            | Self::Char { .. }
            | Self::Int { .. }
            | Self::Float(_)
            | Self::Pointer(_)
            | Self::Array { .. }
            | Self::Function(_) => None,
        }
    }
}

/// Why a database cannot be added to a [`TypeLibrary`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum LoadError {
    /// Two types of the database have this key.
    DuplicateType(String),
    /// A type refers to this key, which the database does not define.
    UnknownType(String),
    /// The library would hold more than 2³² types.
    TooManyTypes,
    /// The database is for another target than those already added: the
    /// library's and the database's.
    Target(Box<(Target, Target)>),
}

impl fmt::Display for LoadError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::DuplicateType(key) => write!(f, "type `{key}` is defined twice"),
            Self::UnknownType(key) => write!(f, "type `{key}` is referred to but not defined"),
            Self::TooManyTypes => write!(f, "more than 2^32 types"),
            Self::Target(targets) => {
                let (expected, found) = targets.as_ref();
                write!(
                    f,
                    "the database is for {}-{}-{}, the library for {}-{}-{}",
                    found.arch, found.os, found.env, expected.arch, expected.os, expected.env
                )
            }
        }
    }
}

impl std::error::Error for LoadError {}

/// Declarations by library (lower case; `None` for any) and name, system
/// calls by name and number, and the types they refer to, for one target.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct TypeLibrary {
    functions: BTreeMap<(Option<String>, String), Declaration>,
    syscalls: BTreeMap<String, Declaration>,
    /// The system calls' names by number, as the first database to number
    /// them says.
    syscall_names: BTreeMap<u64, String>,
    types: Vec<Type>,
    /// The types without a key (primitives, pointers, arrays, function
    /// types), each held once.
    structural: HashMap<Type, TypeId>,
    /// The named types by key, the first added of each key.
    keys: HashMap<String, TypeId>,
    /// The enumerations whose constants are macros in C's headers
    /// ([`Self::macro_constants`]).
    macro_enums: BTreeSet<TypeId>,
    /// The target of the databases added (`None` until one is).
    target: Option<Target>,
}

impl TypeLibrary {
    /// An empty library.
    pub fn new() -> Self {
        Self::default()
    }

    /// The hand-written facts: the [`overrides`] (`data/overrides.toml`,
    /// [`Origin::Override`]), for every target.
    ///
    /// # Panics
    ///
    /// If the embedded overrides do not parse, or a signature of theirs
    /// names a type (a test checks they do not).
    pub fn builtin() -> Self {
        let mut library = Self::new();
        let keys = HashMap::new();
        for entry in overrides::embedded() {
            let prototype = entry.signature.as_ref().map(|signature| Fact {
                value: library
                    .signature(signature, &keys)
                    .unwrap_or_else(|error| panic!("data/overrides.toml: {}: {error}", entry.name)),
                origin: Origin::Override,
            });
            library.declare(
                entry.library.as_deref(),
                &entry.name,
                Declaration {
                    no_return: entry.no_return.then_some(Fact {
                        value: true,
                        origin: Origin::Override,
                    }),
                    no_throw: None,
                    prototype,
                    format: entry.format.clone().map(|value| Fact {
                        value,
                        origin: Origin::Override,
                    }),
                    format_arg: None,
                    alloc_size: None,
                },
            );
        }
        library
    }

    /// Declares function `name` of `library` (`None`: of any library):
    /// each fact replaces one already declared only if it is stronger.
    pub fn declare(&mut self, library: Option<&str>, name: &str, declaration: Declaration) {
        self.functions
            .entry((library.map(str::to_ascii_lowercase), name.to_owned()))
            .or_default()
            .merge(declaration);
    }

    /// What is declared about function `name` imported from `library`
    /// (`None` if the file does not say): a declaration for that library
    /// (matched case-insensitively) first, else one for any library.
    pub fn function(&self, library: Option<&str>, name: &str) -> Option<&Declaration> {
        library
            .and_then(|library| {
                self.functions
                    .get(&(Some(library.to_ascii_lowercase()), name.to_owned()))
            })
            .or_else(|| self.functions.get(&(None, name.to_owned())))
    }

    /// What is declared about system call `name`.
    pub fn syscall(&self, name: &str) -> Option<&Declaration> {
        self.syscalls.get(name)
    }

    /// The name of system call `number` on the target and what is
    /// declared about it, if a database numbers it.
    pub fn syscall_number(&self, number: u64) -> Option<(&str, &Declaration)> {
        let name = self.syscall_names.get(&number)?;
        Some((name, self.syscalls.get(name)?))
    }

    /// Whether the constants of enumeration `id` are macros in C's
    /// headers (`#define O_RDWR 02`), not enumeration constants:
    /// syzkaller's flag sets, and Windows metadata's sets of flags (the
    /// SDK's `#define`s, gathered into one type).
    pub fn macro_constants(&self, id: TypeId) -> bool {
        self.macro_enums.contains(&id)
    }

    /// Type `id` (`None` if it is not of this library).
    pub fn ty(&self, id: TypeId) -> Option<&Type> {
        self.types.get(id.index())
    }

    /// Every type, in table order.
    pub fn types(&self) -> impl Iterator<Item = (TypeId, &Type)> {
        (0u32..).map(TypeId).zip(&self.types)
    }

    /// The named type of key `key` (`struct stat`, `size_t`): the first
    /// added of that key.
    pub fn named(&self, key: &str) -> Option<TypeId> {
        self.keys.get(key).copied()
    }

    /// The keys of the named types, in no order.
    pub fn keys(&self) -> impl Iterator<Item = &str> {
        self.keys.keys().map(String::as_str)
    }

    /// Appends `ty` (a named type, or a placeholder replaced by
    /// [`set`](Self::set) once the types it refers to have ids).
    pub(crate) fn push(&mut self, ty: Type) -> TypeId {
        let id = TypeId(u32::try_from(self.types.len()).unwrap_or(u32::MAX));
        self.types.push(ty);
        id
    }

    /// The id of structural type `ty`, added if the library does not hold
    /// it yet.
    pub(crate) fn intern(&mut self, ty: Type) -> TypeId {
        if let Some(&id) = self.structural.get(&ty) {
            return id;
        }
        let id = self.push(ty.clone());
        self.structural.insert(ty, id);
        id
    }

    /// Replaces type `id` (a placeholder [`push`](Self::push)ed).
    pub(crate) fn set(&mut self, id: TypeId, ty: Type) {
        if let Some(slot) = self.types.get_mut(id.index()) {
            *slot = ty;
        }
    }

    /// The target of the databases added (`None` if none was).
    pub fn target(&self) -> Option<&Target> {
        self.target.as_ref()
    }

    /// The size in bytes of type `id` on the library's target: `None` for
    /// `void`, functions, opaque types, records and arrays of unknown size,
    /// and pointers in a library without a target.
    pub fn size_of(&self, id: TypeId) -> Option<u64> {
        match self.ty(id)? {
            Type::Void | Type::Function(_) | Type::Opaque(_) => None,
            Type::Bool | Type::Char { .. } => Some(1),
            &Type::Int { size, .. } => Some(u64::from(size)),
            &Type::Float(format) => Some(self.float_layout(format)?.0),
            Type::Pointer(_) => self.target.as_ref().map(|t| u64::from(t.pointer_size)),
            &Type::Array { element, count } => self.size_of(element)?.checked_mul(count?),
            Type::Record(record) => record.size,
            Type::Enum(definition) => definition.size.map(u64::from),
            &Type::Typedef(Typedef { target, .. }) => self.size_of(target),
        }
    }

    /// The alignment in bytes of type `id` on the library's target, as
    /// its C ABI lays it out (System V for x86-64 and 32-bit x86, AAPCS64
    /// for AArch64); `None` where [`size_of`](Self::size_of) is, and for
    /// records whose alignment the source does not give.
    pub fn align_of(&self, id: TypeId) -> Option<u64> {
        match self.ty(id)? {
            Type::Void | Type::Function(_) | Type::Opaque(_) => None,
            Type::Bool | Type::Char { .. } => Some(1),
            &Type::Int { size, .. } => self.scalar_align(u64::from(size)),
            &Type::Float(format) => Some(self.float_layout(format)?.1),
            Type::Pointer(_) => {
                let size = u64::from(self.target.as_ref()?.pointer_size);
                self.scalar_align(size)
            }
            &Type::Array { element, .. } => self.align_of(element),
            Type::Record(record) => record.align,
            Type::Enum(definition) => self.scalar_align(u64::from(definition.size?)),
            &Type::Typedef(Typedef { target, .. }) => self.align_of(target),
        }
    }

    /// Whether the target is 32-bit x86, whose System V ABI aligns 8-byte
    /// scalars to 4.
    fn is_i386(&self) -> bool {
        self.target
            .as_ref()
            .is_some_and(|target| matches!(target.arch.as_str(), "x86" | "i386" | "i686"))
    }

    /// The alignment of an integer or pointer of `size` bytes.
    fn scalar_align(&self, size: u64) -> Option<u64> {
        self.target.as_ref()?;
        Some(if self.is_i386() { size.min(4) } else { size })
    }

    /// The size and alignment of a floating-point format.
    fn float_layout(&self, format: FloatFormat) -> Option<(u64, u64)> {
        Some(match format {
            FloatFormat::Half => (2, 2),
            FloatFormat::Single => (4, 4),
            FloatFormat::Double => (8, self.scalar_align(8)?),
            FloatFormat::X87 if self.is_i386() => (12, 4),
            FloatFormat::X87 | FloatFormat::Quad => (16, 16),
        })
    }

    /// Gives each C library function named as a system call it declares
    /// that system call's sets of named values: glibc's wrappers (`mmap`,
    /// `open`, `kill`, `socket`) take the system call's arguments in its
    /// order, so a parameter of a 4-byte integer type (directly or through
    /// typedefs: `int`, `mode_t`) takes the type of the system call's
    /// parameter at its position where that is an enumeration of no size
    /// or 4 bytes: syzkaller's flag and value sets, their values the
    /// target's headers' (`PROT_READ | PROT_WRITE`, `MAP_PRIVATE`,
    /// `O_DIRECTORY`, which differ between targets). Only declarations
    /// for any library; each prototype keeps its origin.
    pub fn with_syscall_flags(&mut self) {
        let keys: Vec<(Option<String>, String)> = self
            .functions
            .keys()
            .filter(|(library, name)| library.is_none() && self.syscalls.contains_key(name))
            .cloned()
            .collect();
        for key in keys {
            let Some(flags) = self.syscall_flags(&key.1) else {
                continue;
            };
            let int = |library: &Self, id: TypeId| library.int_size(id) == Some(4);
            let replaced: Vec<(usize, TypeId)> = self
                .functions
                .get(&key)
                .and_then(|declaration| declaration.prototype.as_ref())
                .map(|prototype| {
                    prototype
                        .value
                        .params
                        .iter()
                        .zip(&flags)
                        .enumerate()
                        .filter_map(|(index, (param, flag))| {
                            flag.filter(|_| int(self, param.ty))
                                .map(|flag| (index, flag))
                        })
                        .collect()
                })
                .unwrap_or_default();
            let Some(prototype) = self
                .functions
                .get_mut(&key)
                .and_then(|declaration| declaration.prototype.as_mut())
            else {
                continue;
            };
            for (index, flag) in replaced {
                if let Some(param) = prototype.value.params.get_mut(index) {
                    param.ty = flag;
                }
            }
        }
    }

    /// Per parameter of system call `name`, its type where that is an
    /// enumeration of no size or 4 bytes ([`Self::with_syscall_flags`]).
    fn syscall_flags(&self, name: &str) -> Option<Vec<Option<TypeId>>> {
        let prototype = self.syscalls.get(name)?.prototype.as_ref()?;
        Some(
            prototype
                .value
                .params
                .iter()
                .map(|param| match self.ty(param.ty) {
                    Some(Type::Enum(definition)) if matches!(definition.size, None | Some(4)) => {
                        Some(param.ty)
                    }
                    Some(_) | None => None,
                })
                .collect(),
        )
    }

    /// The size of integer type `id`, through typedefs.
    fn int_size(&self, id: TypeId) -> Option<u8> {
        match self.ty(id)? {
            &Type::Int { size, .. } => Some(size),
            Type::Typedef(typedef) => self.int_size(typedef.target),
            Type::Void
            | Type::Bool
            | Type::Char { .. }
            | Type::Float(_)
            | Type::Pointer(_)
            | Type::Array { .. }
            | Type::Function(_)
            | Type::Record(_)
            | Type::Enum(_)
            | Type::Opaque(_) => None,
        }
    }

    /// Adds the declarations and types of `database`, each fact with the
    /// origin of the database's source. A system call database
    /// ([`Source::Syzlang`]) declares system calls; the others declare
    /// functions. Each fact replaces one already declared only if it is
    /// stronger. The database's types are added as they are (two
    /// databases' `struct stat` stay two types).
    ///
    /// # Errors
    ///
    /// If two of the database's types have the same key, or a type it
    /// refers to is not defined; the library is then unchanged.
    pub fn add(&mut self, database: &Database) -> Result<(), LoadError> {
        let target = &database.header.target;
        if let Some(expected) = self.target.as_ref().filter(|expected| *expected != target) {
            return Err(LoadError::Target(Box::new((
                expected.clone(),
                target.clone(),
            ))));
        }
        let base = self.types.len();
        let result = self.add_types(database).and_then(|keys| {
            database
                .functions
                .iter()
                .map(|function| Ok((function, self.signature(&function.signature, &keys)?)))
                .collect::<Result<Vec<_>, _>>()
        });
        let functions = match result {
            Ok(functions) => functions,
            Err(error) => {
                self.types.truncate(base);
                self.structural.retain(|_, id| id.index() < base);
                self.keys.retain(|_, id| id.index() < base);
                self.macro_enums.retain(|id| id.index() < base);
                return Err(error);
            }
        };
        self.target = Some(target.clone());
        let origin = database.header.source.origin();
        for (function, signature) in functions {
            let declaration = Declaration {
                no_return: function.no_return.then_some(Fact {
                    value: true,
                    origin,
                }),
                no_throw: function.no_throw.then_some(Fact {
                    value: true,
                    origin,
                }),
                prototype: Some(Fact {
                    value: signature,
                    origin,
                }),
                format: function.format.clone().map(|value| Fact { value, origin }),
                format_arg: (!function.format_arg.is_empty()).then(|| Fact {
                    value: function.format_arg.clone(),
                    origin,
                }),
                alloc_size: function
                    .alloc_size
                    .clone()
                    .map(|value| Fact { value, origin }),
            };
            match database.header.source {
                Source::Syzlang => {
                    if let Some(number) = function.number {
                        self.syscall_names
                            .entry(number)
                            .or_insert_with(|| function.name.clone());
                    }
                    self.syscalls
                        .entry(function.name.clone())
                        .or_default()
                        .merge(declaration);
                }
                Source::Header | Source::Winmd => {
                    self.declare(function.library.as_deref(), &function.name, declaration);
                }
            }
        }
        Ok(())
    }

    /// Adds the named types of `database`, giving the [`TypeId`] of each
    /// key.
    fn add_types<'a>(
        &mut self,
        database: &'a Database,
    ) -> Result<HashMap<&'a str, TypeId>, LoadError> {
        let mut keys = HashMap::with_capacity(database.types.len());
        let first = self.types.len();
        for definition in &database.types {
            let id = self.next_id()?;
            if keys.insert(definition.key(), id).is_some() {
                return Err(LoadError::DuplicateType(definition.key().to_owned()));
            }
            self.keys.entry(definition.key().to_owned()).or_insert(id);
            // A placeholder, replaced below once every key has its id.
            self.types.push(Type::Void);
        }
        for (index, definition) in (first..).zip(&database.types) {
            let ty = match definition {
                Definition::Record(record) => Type::Record(Record {
                    key: record.key.clone(),
                    name: record.name.clone(),
                    union: record.union,
                    size: record.size,
                    align: record.align,
                    fields: record
                        .fields
                        .as_ref()
                        .map(|fields| {
                            fields
                                .iter()
                                .map(|field| {
                                    Ok(Field {
                                        name: field.name.clone(),
                                        ty: self.resolve(&field.ty, &keys)?,
                                        bit_offset: field.bit_offset,
                                        bit_width: field.bit_width,
                                    })
                                })
                                .collect::<Result<_, _>>()
                        })
                        .transpose()?,
                }),
                Definition::Enum(definition) => {
                    // syzkaller's flag sets name the headers' macros; so do
                    // Windows metadata's sets of flags (the SDK's
                    // `#define`s, gathered into one type).
                    let macros = match database.header.source {
                        Source::Syzlang => true,
                        Source::Winmd => definition.flags,
                        Source::Header => false,
                    };
                    if macros && let Ok(id) = u32::try_from(index) {
                        self.macro_enums.insert(TypeId(id));
                    }
                    Type::Enum(definition.clone())
                }
                Definition::Typedef(typedef) => Type::Typedef(Typedef {
                    key: typedef.key.clone(),
                    name: typedef.name.clone(),
                    target: self.resolve(&typedef.target, &keys)?,
                }),
                Definition::Opaque(opaque) => Type::Opaque(opaque.clone()),
            };
            if let Some(slot) = self.types.get_mut(index) {
                *slot = ty;
            }
        }
        Ok(keys)
    }

    fn next_id(&self) -> Result<TypeId, LoadError> {
        u32::try_from(self.types.len())
            .map(TypeId)
            .map_err(|_| LoadError::TooManyTypes)
    }

    fn signature(
        &mut self,
        signature: &Signature<TypeRef>,
        keys: &HashMap<&str, TypeId>,
    ) -> Result<Signature<TypeId>, LoadError> {
        Ok(Signature {
            ret: self.resolve(&signature.ret, keys)?,
            params: signature
                .params
                .iter()
                .map(|param| {
                    Ok(Param {
                        name: param.name.clone(),
                        ty: self.resolve(&param.ty, keys)?,
                    })
                })
                .collect::<Result<_, _>>()?,
            variadic: signature.variadic,
            convention: signature.convention,
        })
    }

    /// The type `ty` refers to: a defined one by its key, a structural one
    /// added if the library does not hold it yet.
    fn resolve(&mut self, ty: &TypeRef, keys: &HashMap<&str, TypeId>) -> Result<TypeId, LoadError> {
        let structural = match ty {
            TypeRef::Named(key) => {
                return keys
                    .get(key.as_str())
                    .copied()
                    .ok_or_else(|| LoadError::UnknownType(key.clone()));
            }
            TypeRef::Void => Type::Void,
            TypeRef::Bool => Type::Bool,
            &TypeRef::Char { signed } => Type::Char { signed },
            &TypeRef::Int { signed, size } => Type::Int { signed, size },
            &TypeRef::Float(format) => Type::Float(format),
            TypeRef::Pointer(target) => Type::Pointer(self.resolve(target, keys)?),
            TypeRef::Array { element, count } => Type::Array {
                element: self.resolve(element, keys)?,
                count: *count,
            },
            TypeRef::Function(signature) => Type::Function(self.signature(signature, keys)?),
        };
        if let Some(&id) = self.structural.get(&structural) {
            return Ok(id);
        }
        let id = self.next_id()?;
        self.types.push(structural.clone());
        self.structural.insert(structural, id);
        Ok(id)
    }
}

#[expect(
    clippy::trivially_copy_pass_by_ref,
    reason = "serde's skip_serializing_if passes a reference"
)]
fn is_false(value: &bool) -> bool {
    !*value
}

#[cfg(test)]
mod tests {
    use super::{Origin, TypeLibrary};

    fn no_return(library: Option<&str>, name: &str) -> Option<(bool, Origin)> {
        let library_ = TypeLibrary::builtin();
        library_
            .function(library, name)
            .and_then(|d| d.no_return)
            .map(|f| (f.value, f.origin))
    }

    #[test]
    fn matches_any_library_or_the_named_one() {
        assert_eq!(no_return(None, "exit"), Some((true, Origin::Override)));
        assert_eq!(
            no_return(Some("api-ms-win-crt-runtime-l1-1-0.dll"), "exit"),
            Some((true, Origin::Override))
        );
        assert_eq!(
            no_return(Some("KERNEL32.dll"), "ExitProcess"),
            Some((true, Origin::Override))
        );
        // Scoped to kernel32: not from another library, not unnamed.
        assert_eq!(no_return(Some("mylib.dll"), "ExitProcess"), None);
        assert_eq!(no_return(None, "ExitProcess"), None);
        assert_eq!(no_return(None, "printf"), None);
    }
}
