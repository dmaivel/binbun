//! The L2 rewrite rules (`crates/binbun-decompile/rules/*.rules`) compiled
//! into `crates/binbun-decompile/src/simplify/rules/generated.rs`: each
//! rule as data (`RULES`, what the proof test reads) and as a matcher
//! function, and the rules filed by the kind of their left side's root.
//!
//! The language is documented in `binbun_decompile::simplify::rules`. The
//! compiler parses each rule, infers every node's width (a linear
//! expression over the width variables), checks that the right side and
//! the conditions use only what the left side binds, and works out the
//! guards the proof cannot see (variables dropped, duplicated or
//! reordered).

