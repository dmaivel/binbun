fn lookup(table: &[(&str, &'static str)], name: &str) -> Option<&'static str> {
    table
        .iter()
        .find(|(text, _)| *text == name)
        .map(|&(_, variant)| variant)
}

// ---------------------------------------------------------------- widths

/// A width: a constant plus multiples of width variables.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
struct Lin {
    constant: i64,
    terms: BTreeMap<String, i64>,
}

impl Lin {
    fn number(value: i64) -> Self {
        Self {
            constant: value,
            terms: BTreeMap::new(),
        }
    }

    fn var(name: &str) -> Self {
        Self {
            constant: 0,
            terms: BTreeMap::from([(name.to_owned(), 1)]),
        }
    }

    fn plus(&self, other: &Self, sign: i64) -> Self {
        let mut sum = self.clone();
        sum.constant += sign * other.constant;
        for (name, coefficient) in &other.terms {
            *sum.terms.entry(name.clone()).or_insert(0) += sign * coefficient;
        }
        sum.terms.retain(|_, coefficient| *coefficient != 0);
        sum
    }

    /// The variable it is, if it is exactly one.
    fn single(&self) -> Option<&str> {
        match (self.constant, self.terms.iter().next(), self.terms.len()) {
            (0, Some((name, 1)), 1) => Some(name),
            _ => None,
        }
    }

    /// Rust code computing it as an `i64` from the bound `w_*` variables.
    fn code(&self) -> String {
        let mut text = String::new();
        for (name, &coefficient) in &self.terms {
            let sign = if coefficient < 0 { " - " } else { " + " };
            if !text.is_empty() || coefficient < 0 {
                text.push_str(sign);
            }
            if coefficient.abs() != 1 {
                let _ = write!(text, "{} * ", coefficient.abs());
            }
            text.push_str(&width_ident(name));
        }
        if text.is_empty() {
            return format!("{}i64", self.constant);
        }
        if self.constant != 0 {
            let sign = if self.constant < 0 { '-' } else { '+' };
            let _ = write!(text, " {sign} {}", self.constant.abs());
        }
        // Only additions and subtractions: the code is used where no
        // operator binds less tightly (arguments, comparisons).
        text.trim_start().to_owned()
    }

    /// `Width { .. }` data, with width variables by index into `names`.
    fn data(&self, names: &[String]) -> String {
        let terms: Vec<String> = self
            .terms
            .iter()
            .map(|(name, coefficient)| {
                let index = names.iter().position(|n| n == name).unwrap_or(0);
                format!("({index}, {coefficient})")
            })
            .collect();
        format!(
            "Width {{ constant: {}, terms: &[{}] }}",
            self.constant,
            terms.join(", ")
        )
    }
}

// ---------------------------------------------------------------- tokens

/// The Rust variable holding width variable `name`'s value.
fn width_ident(name: &str) -> String {
    format!("w_{}", name.to_ascii_lowercase())
}

#[derive(Clone, Debug, PartialEq, Eq)]
enum Token {
    Ident(String),
    Int(i64),
    Punct(&'static str),
}

const PUNCTS: [&str; 17] = [
    "=>", "==", "!=", "<=", ">=", "(", ")", ",", ":", ";", "#", "{", "}", "+", "-", "*", "<",
];

fn tokenize(text: &str) -> Result<Vec<Token>> {
    let mut tokens = Vec::new();
    let mut rest = text.trim_start();
    while !rest.is_empty() {
        let first = rest.chars().next().unwrap_or(' ');
        if first.is_ascii_alphabetic() || first == '_' {
            // Lower-case names may hold hyphens (operations, rule names).
            let hyphens = first.is_ascii_lowercase();
            let end = rest
                .char_indices()
                .find(|&(_, c)| !(c.is_ascii_alphanumeric() || c == '_' || (hyphens && c == '-')))
                .map_or(rest.len(), |(index, _)| index);
            tokens.push(Token::Ident(rest[..end].to_owned()));
            rest = &rest[end..];
        } else if first.is_ascii_digit() {
            let end = rest
                .char_indices()
                .find(|&(_, c)| !c.is_ascii_alphanumeric())
                .map_or(rest.len(), |(index, _)| index);
            let digits = &rest[..end];
            let value = match digits.strip_prefix("0x") {
                Some(hex) => u64::from_str_radix(hex, 16)
                    .map(u64::cast_signed)
                    .map_err(|e| format!("`{digits}`: {e}"))?,
                None => digits.parse().map_err(|e| format!("`{digits}`: {e}"))?,
            };
            tokens.push(Token::Int(value));
            rest = &rest[end..];
        } else if first == '>' && !rest.starts_with(">=") {
            tokens.push(Token::Punct(">"));
            rest = &rest[1..];
        } else {
            let punct = PUNCTS
                .iter()
                .find(|p| rest.starts_with(**p))
                .ok_or_else(|| format!("unexpected `{first}`"))?;
            tokens.push(Token::Punct(punct));
            rest = &rest[punct.len()..];
        }
        rest = rest.trim_start();
    }
    Ok(tokens)
}

// ---------------------------------------------------------------- syntax

/// A node of a side being built: operands are indices into the same side.
#[derive(Clone, Debug, PartialEq, Eq)]
enum Kind {
    Var(usize),
    Const(usize),
    Int(i64),
    WidthValue(Lin),
    Unary(&'static str, usize),
    Binary(&'static str, usize, usize),
    Flag(&'static str, usize, usize, usize),
    Extract(usize, Lin, Lin),
    Concat(usize, usize),
    Extend(bool, usize, Lin),
    Select(usize, usize, usize),
}

impl Kind {
    fn operands(&self) -> Vec<usize> {
        match self {
            Self::Var(_) | Self::Const(_) | Self::Int(_) | Self::WidthValue(_) => Vec::new(),
            Self::Unary(_, a) | Self::Extract(a, ..) | Self::Extend(_, a, _) => vec![*a],
            Self::Binary(_, a, b) | Self::Concat(a, b) => vec![*a, *b],
            Self::Flag(_, a, b, c) | Self::Select(a, b, c) => vec![*a, *b, *c],
        }
    }
}

#[derive(Clone, Debug)]
struct Side {
    nodes: Vec<Kind>,
    /// Width annotations (on variables, constants and literals).
    annotations: Vec<Option<Lin>>,
    widths: Vec<Option<Lin>>,
}

impl Side {
    fn new() -> Self {
        Self {
            nodes: Vec::new(),
            annotations: Vec::new(),
            widths: Vec::new(),
        }
    }

    fn push(&mut self, kind: Kind, annotation: Option<Lin>) -> usize {
        self.nodes.push(kind);
        self.annotations.push(annotation);
        self.widths.push(None);
        self.nodes.len() - 1
    }
}

/// Names of pattern and constant variables, shared by a rule's sides.
#[derive(Default)]
struct Names {
    vars: Vec<String>,
    constants: Vec<String>,
}

struct Parser<'a> {
    tokens: &'a [Token],
    at: usize,
}

impl Parser<'_> {
    fn peek(&self) -> Option<&Token> {
        self.tokens.get(self.at)
    }

    fn next(&mut self) -> Result<Token> {
        let token = self.peek().cloned().ok_or("unexpected end of rule")?;
        self.at += 1;
        Ok(token)
    }

    fn eat(&mut self, punct: &str) -> bool {
        if matches!(self.peek(), Some(Token::Punct(p)) if *p == punct) {
            self.at += 1;
            true
        } else {
            false
        }
    }

    fn expect(&mut self, punct: &str) -> Result<()> {
        if self.eat(punct) {
            Ok(())
        } else {
            Err(format!("expected `{punct}`, found {:?}", self.peek()).into())
        }
    }

    fn ident(&mut self) -> Result<String> {
        match self.next()? {
            Token::Ident(name) => Ok(name),
            other @ (Token::Int(_) | Token::Punct(_)) => {
                Err(format!("expected a name, found {other:?}").into())
            }
        }
    }

    fn width(&mut self) -> Result<Lin> {
        let mut sum = self.width_term()?;
        loop {
            if self.eat("+") {
                sum = sum.plus(&self.width_term()?, 1);
            } else if self.eat("-") {
                sum = sum.plus(&self.width_term()?, -1);
            } else {
                return Ok(sum);
            }
        }
    }

    fn width_term(&mut self) -> Result<Lin> {
        match self.next()? {
            Token::Int(value) => {
                if self.eat("*") {
                    let name = self.ident()?;
                    Ok(Lin {
                        constant: 0,
                        terms: BTreeMap::from([(name, value)]),
                    })
                } else {
                    Ok(Lin::number(value))
                }
            }
            Token::Ident(name) if name.starts_with(|c: char| c.is_ascii_uppercase()) => {
                Ok(Lin::var(&name))
            }
            other @ (Token::Ident(_) | Token::Punct(_)) => {
                Err(format!("expected a width, found {other:?}").into())
            }
        }
    }

    fn annotation(&mut self) -> Result<Option<Lin>> {
        if self.eat(":") {
            Ok(Some(self.width()?))
        } else {
            Ok(None)
        }
    }

    fn expr(&mut self, side: &mut Side, names: &mut Names) -> Result<usize> {
        if self.eat("#") {
            let name = self.ident()?;
            let index = position_or_push(&mut names.constants, &name);
            let annotation = self.annotation()?;
            return Ok(side.push(Kind::Const(index), annotation));
        }
        if self.eat("{") {
            let width = self.width()?;
            self.expect("}")?;
            let annotation = self.annotation()?;
            return Ok(side.push(Kind::WidthValue(width), annotation));
        }
        let negative = self.eat("-");
        match self.next()? {
            Token::Int(value) => {
                let value = if negative { -value } else { value };
                let annotation = self.annotation()?;
                Ok(side.push(Kind::Int(value), annotation))
            }
            Token::Ident(name) if !negative => {
                if !self.eat("(") {
                    let index = position_or_push(&mut names.vars, &name);
                    let annotation = self.annotation()?;
                    return Ok(side.push(Kind::Var(index), annotation));
                }
                let kind = self.call(&name, side, names)?;
                self.expect(")")?;
                Ok(side.push(kind, None))
            }
            other @ (Token::Ident(_) | Token::Punct(_)) => {
                Err(format!("expected an expression, found {other:?}").into())
            }
        }
    }

    fn call(&mut self, name: &str, side: &mut Side, names: &mut Names) -> Result<Kind> {
        let mut operands = |parser: &mut Self, count: usize| -> Result<Vec<usize>> {
            let mut list = Vec::new();
            for index in 0..count {
                if index > 0 {
                    parser.expect(",")?;
                }
                list.push(parser.expr(side, names)?);
            }
            Ok(list)
        };
        Ok(match name {
            "extract" => {
                let value = operands(self, 1)?[0];
                self.expect(",")?;
                let offset = self.width()?;
                self.expect(",")?;
                Kind::Extract(value, offset, self.width()?)
            }
            "zext" | "sext" => {
                let value = operands(self, 1)?[0];
                self.expect(",")?;
                Kind::Extend(name == "sext", value, self.width()?)
            }
            "concat" => {
                let list = operands(self, 2)?;
                Kind::Concat(list[0], list[1])
            }
            "select" => {
                let list = operands(self, 3)?;
                Kind::Select(list[0], list[1], list[2])
            }
            _ => {
                if let Some(op) = lookup(&UNARY, name) {
                    Kind::Unary(op, operands(self, 1)?[0])
                } else if let Some(op) = lookup(&BINARY, name) {
                    let list = operands(self, 2)?;
                    Kind::Binary(op, list[0], list[1])
                } else if let Some(op) = lookup(&FLAG, name) {
                    let list = operands(self, 3)?;
                    Kind::Flag(op, list[0], list[1], list[2])
                } else {
                    return Err(format!("unknown operation `{name}`").into());
                }
            }
        })
    }
}

fn position_or_push(list: &mut Vec<String>, name: &str) -> usize {
    if let Some(index) = list.iter().position(|n| n == name) {
        index
    } else {
        list.push(name.to_owned());
        list.len() - 1
    }
}

/// A rule as written, parsed.
struct Parsed {
    name: String,
    group: String,
    text: String,
    names: Names,
    lhs: Side,
    rhs: Side,
    conditions: Side,
    holds: Vec<usize>,
    constraints: Vec<(Lin, &'static str, Lin)>,
    claimed: BTreeMap<String, Vec<u16>>,
}

fn parse_rule(text: &str, group: &str) -> Result<Parsed> {
    let tokens = tokenize(text)?;
    let mut p = Parser {
        tokens: &tokens,
        at: 0,
    };
    if p.ident()? != "rule" {
        return Err("a rule starts with `rule`".into());
    }
    let name = p.ident()?;
    p.expect(":")?;
    let mut names = Names::default();
    let mut lhs = Side::new();
    p.expr(&mut lhs, &mut names)?;
    p.expect("=>")?;
    let known = (names.vars.len(), names.constants.len());
    let mut rhs = Side::new();
    p.expr(&mut rhs, &mut names)?;
    if (names.vars.len(), names.constants.len()) != known {
        return Err(
            format!("{name}: the right side uses a variable the left does not bind").into(),
        );
    }
    let mut conditions = Side::new();
    let mut holds = Vec::new();
    let mut constraints = Vec::new();
    let mut claimed = BTreeMap::new();
    while let Some(Token::Ident(word)) = p.peek().cloned() {
        p.at += 1;
        match word.as_str() {
            "if" => loop {
                if matches!(p.peek(), Some(Token::Ident(n)) if n.starts_with(|c: char| c.is_ascii_lowercase()))
                    || matches!(p.peek(), Some(Token::Punct("#" | "{")))
                {
                    holds.push(p.expr(&mut conditions, &mut names)?);
                } else {
                    let left = p.width()?;
                    let relation = match p.next()? {
                        Token::Punct(r @ ("==" | "!=" | "<" | "<=" | ">" | ">=")) => r,
                        other @ (Token::Punct(_) | Token::Ident(_) | Token::Int(_)) => {
                            return Err(format!("expected a relation, found {other:?}").into());
                        }
                    };
                    constraints.push((left, relation, p.width()?));
                }
                if !p.eat(",") {
                    break;
                }
            },
            "widths" => loop {
                let var = p.ident()?;
                if p.ident()? != "in" {
                    return Err("expected `in`".into());
                }
                let mut list = Vec::new();
                while let Some(Token::Int(value)) = p.peek().cloned() {
                    p.at += 1;
                    list.push(u16::try_from(value)?);
                }
                claimed.insert(var, list);
                if !p.eat(";") {
                    break;
                }
            },
            other => return Err(format!("{name}: unexpected `{other}`").into()),
        }
    }
    if p.at != tokens.len() {
        return Err(format!("{name}: trailing {:?}", p.peek()).into());
    }
    if (names.vars.len(), names.constants.len()) != known
        || conditions
            .nodes
            .iter()
            .any(|kind| matches!(kind, Kind::Var(_)))
    {
        return Err(
            format!("{name}: a condition uses a pattern variable or an unbound constant").into(),
        );
    }
    Ok(Parsed {
        name,
        group: group.to_owned(),
        text: text.split_whitespace().collect::<Vec<_>>().join(" "),
        names,
        lhs,
        rhs,
        conditions,
        holds,
        constraints,
        claimed,
    })
}

// ---------------------------------------------------------------- widths inferred

/// Unifies two width slots; whether either changed.
fn unify(a: &mut Option<Lin>, b: &mut Option<Lin>, what: &str) -> Result<bool> {
    match (a.as_ref(), b.as_ref()) {
        (Some(x), Some(y)) if x != y => {
            Err(format!("{what}: widths {x:?} and {y:?} differ").into())
        }
        (Some(x), None) => {
            *b = Some(x.clone());
            Ok(true)
        }
        (None, Some(y)) => {
            *a = Some(y.clone());
            Ok(true)
        }
        _ => Ok(false),
    }
}

fn set(slot: &mut Option<Lin>, value: Lin, what: &str) -> Result<bool> {
    unify(slot, &mut Some(value), what)
}

/// Unifies the width slots `a` and `b` of `widths`.
fn same_width(widths: &mut [Option<Lin>], a: usize, b: usize, what: &str) -> Result<bool> {
    let (mut x, mut y) = (widths[a].clone(), widths[b].clone());
    let changed = unify(&mut x, &mut y, what)?;
    widths[a] = x;
    widths[b] = y;
    Ok(changed)
}

/// One round of width inference over `side`; whether anything changed.
fn infer_side(
    side: &mut Side,
    vars: &mut [Option<Lin>],
    constants: &mut [Option<Lin>],
    name: &str,
) -> Result<bool> {
    let mut changed = false;
    let one = Lin::number(1);
    for index in 0..side.nodes.len() {
        if let Some(annotation) = side.annotations[index].clone() {
            changed |= set(&mut side.widths[index], annotation, name)?;
        }
        let widths = &mut side.widths;
        match side.nodes[index].clone() {
            Kind::Var(v) => changed |= unify(&mut widths[index], &mut vars[v], name)?,
            Kind::Const(c) => changed |= unify(&mut widths[index], &mut constants[c], name)?,
            Kind::Int(_) | Kind::WidthValue(_) => {}
            Kind::Unary(op, a) => {
                if op == "EvenParity8" {
                    changed |= set(&mut widths[index], one.clone(), name)?;
                } else {
                    changed |= same_width(widths, index, a, name)?;
                }
            }
            Kind::Binary(op, a, b) => {
                changed |= same_width(widths, a, b, name)?;
                if COMPARISONS.contains(&op) {
                    changed |= set(&mut widths[index], one.clone(), name)?;
                } else {
                    changed |= same_width(widths, index, a, name)?;
                    changed |= same_width(widths, a, b, name)?;
                }
            }
            Kind::Flag(_, a, b, c) => {
                changed |= same_width(widths, a, b, name)?;
                changed |= same_width(widths, b, c, name)?;
                changed |= same_width(widths, a, b, name)?;
                changed |= set(&mut widths[index], one.clone(), name)?;
            }
            Kind::Select(c, t, o) => {
                changed |= set(&mut widths[c], one.clone(), name)?;
                changed |= same_width(widths, t, o, name)?;
                changed |= same_width(widths, index, t, name)?;
                changed |= same_width(widths, t, o, name)?;
            }
            Kind::Extract(_, _, width) | Kind::Extend(_, _, width) => {
                changed |= set(&mut widths[index], width, name)?;
            }
            Kind::Concat(high, low) => {
                let (wh, wl, own) = (
                    widths[high].clone(),
                    widths[low].clone(),
                    widths[index].clone(),
                );
                match (wh, wl, own) {
                    (Some(h), Some(l), _) => {
                        changed |= set(&mut widths[index], h.plus(&l, 1), name)?;
                    }
                    (Some(h), None, Some(o)) => {
                        changed |= set(&mut widths[low], o.plus(&h, -1), name)?;
                    }
                    (None, Some(l), Some(o)) => {
                        changed |= set(&mut widths[high], o.plus(&l, -1), name)?;
                    }
                    _ => {}
                }
            }
        }
    }
    Ok(changed)
}

/// A rule compiled: widths inferred, guards worked out.
struct Compiled {
    parsed: Parsed,
    vars: Vec<Lin>,
    constants: Vec<Lin>,
    width_vars: Vec<String>,
}

fn infer(mut parsed: Parsed) -> Result<Compiled> {
    let name = parsed.name.clone();
    let mut vars = vec![None; parsed.names.vars.len()];
    let mut constants = vec![None; parsed.names.constants.len()];
    loop {
        let mut changed = infer_side(&mut parsed.lhs, &mut vars, &mut constants, &name)?;
        changed |= infer_side(&mut parsed.rhs, &mut vars, &mut constants, &name)?;
        changed |= infer_side(&mut parsed.conditions, &mut vars, &mut constants, &name)?;
        let (l, r) = (parsed.lhs.nodes.len() - 1, parsed.rhs.nodes.len() - 1);
        let (mut wl, mut wr) = (parsed.lhs.widths[l].take(), parsed.rhs.widths[r].take());
        changed |= unify(&mut wl, &mut wr, &name)?;
        parsed.lhs.widths[l] = wl;
        parsed.rhs.widths[r] = wr;
        for &root in &parsed.holds {
            changed |= set(&mut parsed.conditions.widths[root], Lin::number(1), &name)?;
        }
        if !changed {
            break;
        }
    }
    let unknown = |side: &Side| side.widths.iter().any(Option::is_none);
    if unknown(&parsed.lhs) || unknown(&parsed.rhs) || unknown(&parsed.conditions) {
        return Err(format!("{name}: cannot infer every width (annotate with `:W`)").into());
    }
    let vars: Vec<Lin> = vars.into_iter().map(Option::unwrap_or_default).collect();
    let constants: Vec<Lin> = constants
        .into_iter()
        .map(Option::unwrap_or_default)
        .collect();
    let mut width_vars = BTreeSet::new();
    let mut collect = |lin: &Lin| width_vars.extend(lin.terms.keys().cloned());
    for side in [&parsed.lhs, &parsed.rhs, &parsed.conditions] {
        for lin in side.widths.iter().flatten() {
            collect(lin);
        }
        for kind in &side.nodes {
            match kind {
                Kind::WidthValue(lin) | Kind::Extend(_, _, lin) => collect(lin),
                Kind::Extract(_, offset, width) => {
                    collect(offset);
                    collect(width);
                }
                Kind::Var(_)
                | Kind::Const(_)
                | Kind::Int(_)
                | Kind::Unary(..)
                | Kind::Binary(..)
                | Kind::Flag(..)
                | Kind::Concat(..)
                | Kind::Select(..) => {}
            }
        }
    }
    for (left, _, right) in &parsed.constraints {
        collect(left);
        collect(right);
    }
    for var in parsed.claimed.keys() {
        if !width_vars.contains(var) {
            return Err(format!("{name}: claims widths for unknown `{var}`").into());
        }
    }
    Ok(Compiled {
        parsed,
        vars,
        constants,
        width_vars: width_vars.into_iter().collect(),
    })
}

