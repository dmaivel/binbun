/// The rule's matcher function.
fn matcher(rule: &Compiled, index: usize) -> Result<String> {
    let p = &rule.parsed;
    let lhs = &p.lhs;
    let root = lhs.nodes.len() - 1;
    let mut code = String::new();
    let mut sites: Vec<(String, Lin)> = Vec::new();
    let mut literals: Vec<(String, Lin, String)> = Vec::new();
    // Conditions under which the rule does not apply.
    let mut guards: Vec<String> = Vec::new();
    let mut bound_vars: BTreeMap<usize, String> = BTreeMap::new();
    let mut lhs_order: Vec<usize> = Vec::new();
    let mut lhs_count: BTreeMap<usize, usize> = BTreeMap::new();
    let mut bound_constants: BTreeSet<usize> = BTreeSet::new();
    // Pre-order, operands left to right: evaluation order of first uses.
    let mut work = vec![(root, "root".to_owned())];
    while let Some((node, id)) = work.pop() {
        let operand = |i: usize| format!("e{i}");
        match &lhs.nodes[node] {
            Kind::Var(v) => {
                *lhs_count.entry(*v).or_insert(0) += 1;
                if let Some(first) = bound_vars.get(v) {
                    guards.push(format!("!m.same({first}, {id})"));
                } else {
                    let _ = writeln!(code, "let v{v} = {id};");
                    bound_vars.insert(*v, format!("v{v}"));
                    lhs_order.push(*v);
                    sites.push((format!("m.width(v{v})?"), rule.vars[*v].clone()));
                }
            }
            Kind::Const(c) => {
                if bound_constants.insert(*c) {
                    let _ = writeln!(code, "let ce{c} = {id};");
                    let _ = writeln!(code, "let c{c} = m.constant(ce{c})?;");
                    sites.push((
                        format!("i64::from(c{c}.width())"),
                        rule.constants[*c].clone(),
                    ));
                } else {
                    guards.push(format!("m.constant({id}) != Some(c{c})"));
                }
            }
            Kind::Int(value) => {
                let width = lhs.widths[node].clone().unwrap_or_default();
                if width.single().is_some() {
                    sites.push((format!("m.width({id})?"), width.clone()));
                }
                literals.push((id, width, format!("{value}i64")));
            }
            Kind::WidthValue(lin) => {
                let width = lhs.widths[node].clone().unwrap_or_default();
                if width.single().is_some() {
                    sites.push((format!("m.width({id})?"), width.clone()));
                }
                literals.push((id, width, lin.code()));
            }
            Kind::Unary(op, a) => {
                let _ = writeln!(
                    code,
                    "let Expr::Unary(Unary::{op}, {}) = m.expr({id})? else {{ return None; }};",
                    operand(*a)
                );
                work.push((*a, operand(*a)));
            }
            Kind::Binary(op, a, b) => {
                let _ = writeln!(
                    code,
                    "let Expr::Binary(Binary::{op}, {}, {}) = m.expr({id})? else {{ return None; }};",
                    operand(*a),
                    operand(*b)
                );
                work.push((*b, operand(*b)));
                work.push((*a, operand(*a)));
            }
            Kind::Flag(op, a, b, c) => {
                let _ = writeln!(
                    code,
                    "let Expr::Flag(Flag::{op}, {}, {}, {}) = m.expr({id})? else {{ return None; }};",
                    operand(*a),
                    operand(*b),
                    operand(*c)
                );
                work.push((*c, operand(*c)));
                work.push((*b, operand(*b)));
                work.push((*a, operand(*a)));
            }
            Kind::Extract(a, offset, width) => {
                let _ = writeln!(
                    code,
                    "let Expr::Extract {{ value: {}, offset: o{node}, width: n{node} }} = m.expr({id})? else {{ return None; }};",
                    operand(*a)
                );
                sites.push((format!("i64::from(o{node})"), offset.clone()));
                sites.push((format!("i64::from(n{node})"), width.clone()));
                work.push((*a, operand(*a)));
            }
            Kind::Concat(high, low) => {
                let _ = writeln!(
                    code,
                    "let Expr::Concat {{ high: {}, low: {} }} = m.expr({id})? else {{ return None; }};",
                    operand(*high),
                    operand(*low)
                );
                work.push((*low, operand(*low)));
                work.push((*high, operand(*high)));
            }
            Kind::Extend(signed, a, width) => {
                let _ = writeln!(
                    code,
                    "let Expr::Extend {{ signed: {signed}, value: {}, width: n{node} }} = m.expr({id})? else {{ return None; }};",
                    operand(*a)
                );
                sites.push((format!("i64::from(n{node})"), width.clone()));
                work.push((*a, operand(*a)));
            }
            Kind::Select(c, t, o) => {
                let _ = writeln!(
                    code,
                    "let Expr::Select {{ condition: {}, then: {}, otherwise: {} }} = m.expr({id})? else {{ return None; }};",
                    operand(*c),
                    operand(*t),
                    operand(*o)
                );
                work.push((*o, operand(*o)));
                work.push((*t, operand(*t)));
                work.push((*c, operand(*c)));
            }
        }
    }
    // Width variables: bound by the first site that is exactly one.
    let mut bound: BTreeSet<String> = BTreeSet::new();
    let mut checks: Vec<(String, Lin)> = Vec::new();
    for (site, lin) in sites {
        match lin.single() {
            Some(var) if !bound.contains(var) => {
                let _ = writeln!(code, "let {} = {site};", width_ident(var));
                bound.insert(var.to_owned());
            }
            _ => checks.push((site, lin)),
        }
    }
    for var in &rule.width_vars {
        if !bound.contains(var) {
            return Err(format!("{}: the left side does not bind `{var}`", p.name).into());
        }
        let claimed = p
            .claimed
            .get(var)
            .cloned()
            .unwrap_or(DEFAULT_WIDTHS.to_vec());
        let list: Vec<String> = claimed.iter().map(u16::to_string).collect();
        let _ = writeln!(
            code,
            "if !claimed({}, &[{}]) {{ return None; }}",
            width_ident(var),
            list.join(", ")
        );
    }
    for (site, lin) in checks {
        let _ = writeln!(code, "if {site} != {} {{ return None; }}", lin.code());
    }
    for (id, width, value) in literals {
        let _ = writeln!(
            code,
            "if !m.literal({id}, {}, {value}) {{ return None; }}",
            width.code()
        );
    }
    for (left, relation, right) in &p.constraints {
        let negated = match *relation {
            "==" => "!=",
            "!=" => "==",
            "<" => ">=",
            "<=" => ">",
            ">" => "<=",
            _ => "<",
        };
        let _ = writeln!(
            code,
            "if {} {negated} {} {{ return None; }}",
            left.code(),
            right.code()
        );
    }
    // What the right side does with the variables.
    let mut rhs_count: BTreeMap<usize, usize> = BTreeMap::new();
    let mut rhs_order: Vec<usize> = Vec::new();
    let mut stack = vec![p.rhs.nodes.len() - 1];
    while let Some(node) = stack.pop() {
        if let Kind::Var(v) = p.rhs.nodes[node] {
            *rhs_count.entry(v).or_insert(0) += 1;
            if !rhs_order.contains(&v) {
                rhs_order.push(v);
            }
        }
        stack.extend(p.rhs.nodes[node].operands().into_iter().rev());
    }
    for (&v, &count) in &lhs_count {
        let after = rhs_count.get(&v).copied().unwrap_or(0);
        if after == 0 {
            guards.push(format!("!m.harmless(v{v})"));
        } else if after > count {
            guards.push(format!("!m.defined(v{v})"));
        }
    }
    let kept: Vec<usize> = lhs_order
        .iter()
        .copied()
        .filter(|v| rhs_order.contains(v))
        .collect();
    if kept != rhs_order {
        let list: Vec<String> = rhs_order.iter().map(|v| format!("v{v}")).collect();
        guards.push(format!("!m.alone(&[{}])", list.join(", ")));
    }
    for guard in guards {
        let _ = writeln!(code, "if {guard} {{ return None; }}");
    }
    // Side conditions over constants.
    for (node, kind) in p.conditions.nodes.iter().enumerate() {
        let width = p.conditions.widths[node].clone().unwrap_or_default();
        let value = match kind {
            Kind::Var(_) => return Err(format!("{}: a variable in a condition", p.name).into()),
            Kind::Const(c) => format!("c{c}"),
            Kind::Int(value) => format!("int({}, {value}i64)?", width.code()),
            Kind::WidthValue(lin) => format!("int({}, {})?", width.code(), lin.code()),
            Kind::Unary(op, a) => format!("un(Unary::{op}, k{a})?"),
            Kind::Binary(op, a, b) => format!("bin(Binary::{op}, k{a}, k{b})?"),
            Kind::Flag(op, a, b, c) => format!("flag(Flag::{op}, k{a}, k{b}, k{c})?"),
            Kind::Extract(a, offset, width) => {
                format!("extract(k{a}, {}, {})?", offset.code(), width.code())
            }
            Kind::Concat(h, l) => format!("concat(k{h}, k{l})?"),
            Kind::Extend(signed, a, width) => format!("extend({signed}, k{a}, {})?", width.code()),
            Kind::Select(c, t, o) => format!("select(k{c}, k{t}, k{o})?"),
        };
        let _ = writeln!(code, "let k{node} = {value};");
    }
    for root in &p.holds {
        let _ = writeln!(code, "if !holds(k{root}) {{ return None; }}");
    }
    // The right side.
    for (node, kind) in p.rhs.nodes.iter().enumerate() {
        let width = p.rhs.widths[node].clone().unwrap_or_default();
        let value = match kind {
            Kind::Var(v) => format!("v{v}"),
            Kind::Const(c) => format!("ce{c}"),
            Kind::Int(value) => format!("m.int({}, {value}i64)?", width.code()),
            Kind::WidthValue(lin) => format!("m.int({}, {})?", width.code(), lin.code()),
            Kind::Unary(op, a) => format!("m.unary(Unary::{op}, r{a})?"),
            Kind::Binary(op, a, b) => format!("m.binary(Binary::{op}, r{a}, r{b})?"),
            Kind::Flag(op, a, b, c) => format!("m.add(Expr::Flag(Flag::{op}, r{a}, r{b}, r{c}))?"),
            Kind::Extract(a, offset, width) => {
                format!("m.extract(r{a}, {}, {})?", offset.code(), width.code())
            }
            Kind::Concat(h, l) => format!("m.concat(r{h}, r{l})?"),
            Kind::Extend(signed, a, width) => {
                format!("m.extend({signed}, r{a}, {})?", width.code())
            }
            Kind::Select(c, t, o) => format!("m.select(r{c}, r{t}, r{o})?"),
        };
        let _ = writeln!(code, "let r{node} = {value};");
    }
    let _ = writeln!(code, "Some(r{})", p.rhs.nodes.len() - 1);
    Ok(format!(
        "/// `{}` ({}).\nfn rule_{index}(m: &mut Matcher<'_>, root: ExprId) -> Option<ExprId> {{\n{code}}}\n",
        p.name, p.group
    ))
}

/// The `Shape` a rule is filed under: its left root's kind.
fn shape(kind: &Kind) -> Option<String> {
    Some(match kind {
        Kind::Unary(op, _) => format!("Shape::Unary(Unary::{op})"),
        Kind::Binary(op, ..) => format!("Shape::Binary(Binary::{op})"),
        Kind::Flag(op, ..) => format!("Shape::Flag(Flag::{op})"),
        Kind::Extract(..) => "Shape::Extract".to_owned(),
        Kind::Concat(..) => "Shape::Concat".to_owned(),
        Kind::Extend(..) => "Shape::Extend".to_owned(),
        Kind::Select(..) => "Shape::Select".to_owned(),
        Kind::Var(_) | Kind::Const(_) | Kind::Int(_) | Kind::WidthValue(_) => return None,
    })
}

/// A side as `&[Node]` data.
fn nodes(side: &Side, names: &[String]) -> String {
    let list: Vec<String> = side
        .nodes
        .iter()
        .enumerate()
        .map(|(index, kind)| {
            let width = || side.widths[index].clone().unwrap_or_default().data(names);
            match kind {
                Kind::Var(v) => format!("Node::Var({v})"),
                Kind::Const(c) => format!("Node::Const({c})"),
                Kind::Int(value) => format!(
                    "Node::Literal {{ value: Literal::Int({value}), width: {} }}",
                    width()
                ),
                Kind::WidthValue(lin) => format!(
                    "Node::Literal {{ value: Literal::Width({}), width: {} }}",
                    lin.data(names),
                    width()
                ),
                Kind::Unary(op, a) => format!("Node::Unary(Unary::{op}, {a})"),
                Kind::Binary(op, a, b) => format!("Node::Binary(Binary::{op}, {a}, {b})"),
                Kind::Flag(op, a, b, c) => format!("Node::Flag(Flag::{op}, {a}, {b}, {c})"),
                Kind::Extract(a, offset, w) => format!(
                    "Node::Extract {{ value: {a}, offset: {}, width: {} }}",
                    offset.data(names),
                    w.data(names)
                ),
                Kind::Concat(h, l) => format!("Node::Concat {{ high: {h}, low: {l} }}"),
                Kind::Extend(signed, a, w) => format!(
                    "Node::Extend {{ signed: {signed}, value: {a}, width: {} }}",
                    w.data(names)
                ),
                Kind::Select(c, t, o) => {
                    format!("Node::Select {{ condition: {c}, then: {t}, otherwise: {o} }}")
                }
            }
        })
        .collect();
    format!("&[{}]", list.join(", "))
}

/// The rule as `Rule { .. }` data.
fn data(rule: &Compiled) -> String {
    let p = &rule.parsed;
    let names = &rule.width_vars;
    let widths: Vec<String> = names
        .iter()
        .map(|name| {
            let claimed = p
                .claimed
                .get(name)
                .cloned()
                .unwrap_or(DEFAULT_WIDTHS.to_vec());
            let list: Vec<String> = claimed.iter().map(u16::to_string).collect();
            format!(
                "WidthVar {{ name: {name:?}, claimed: &[{}] }}",
                list.join(", ")
            )
        })
        .collect();
    let table = |list: &[String], widths: &[Lin]| -> String {
        let items: Vec<String> = list
            .iter()
            .zip(widths)
            .map(|(name, width)| format!("({name:?}, {})", width.data(names)))
            .collect();
        format!("&[{}]", items.join(", "))
    };
    let constraints: Vec<String> = p
        .constraints
        .iter()
        .map(|(left, relation, right)| {
            // `>` and `>=` as `<` and `<=` the other way round.
            let (left, relation, right) = match *relation {
                "==" => (left, "Eq", right),
                "!=" => (left, "Ne", right),
                "<" => (left, "Lt", right),
                "<=" => (left, "Le", right),
                ">" => (right, "Lt", left),
                _ => (right, "Le", left),
            };
            format!(
                "Constraint {{ left: {}, relation: Relation::{relation}, right: {} }}",
                left.data(names),
                right.data(names)
            )
        })
        .collect();
    let holds: Vec<String> = p.holds.iter().map(usize::to_string).collect();
    format!(
        "Rule {{ name: {:?}, group: {:?}, text: {:?}, widths: &[{}], vars: {}, constants: {}, lhs: {}, rhs: {}, constraints: &[{}], conditions: {}, holds: &[{}] }}",
        p.name,
        p.group,
        p.text,
        widths.join(", "),
        table(&p.names.vars, &rule.vars),
        table(&p.names.constants, &rule.constants),
        nodes(&p.lhs, names),
        nodes(&p.rhs, names),
        constraints.join(", "),
        nodes(&p.conditions, names),
        holds.join(", ")
    )
}

/// The rules of `text` (a file of group `group`): one per `rule` line, with
/// the indented lines after it; `#` starts a comment line.
fn rules_of(text: &str, group: &str) -> Result<Vec<Compiled>> {
    let mut rules: Vec<String> = Vec::new();
    for line in text.lines() {
        let trimmed = line.trim();
        if trimmed.is_empty() || line.starts_with('#') {
            continue;
        }
        if line.starts_with(char::is_whitespace) {
            let last = rules
                .last_mut()
                .ok_or("a continuation line before any rule")?;
            last.push(' ');
            last.push_str(trimmed);
        } else {
            rules.push(trimmed.to_owned());
        }
    }
    rules
        .iter()
        .map(|text| {
            parse_rule(text, group)
                .and_then(infer)
                .map_err(|e| format!("{group}: {text}: {e}").into())
        })
        .collect()
}

/// The generated matcher file.
pub fn generate(root: &Path) -> Result<Vec<GeneratedFile>> {
    let directory = root.join("crates/binbun-decompile/rules");
    let mut paths: Vec<PathBuf> = std::fs::read_dir(&directory)
        .map_err(|e| format!("{}: {e}", directory.display()))?
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| path.extension().is_some_and(|ext| ext == "rules"))
        .collect();
    paths.sort();
    let mut rules = Vec::new();
    for path in &paths {
        let group = path
            .file_stem()
            .and_then(|stem| stem.to_str())
            .ok_or("a rules file without a name")?;
        let text = std::fs::read_to_string(path)?;
        rules.extend(rules_of(&text, group)?);
    }
    let mut seen = BTreeSet::new();
    for rule in &rules {
        if !seen.insert(rule.parsed.name.clone()) {
            return Err(format!("two rules named `{}`", rule.parsed.name).into());
        }
    }
    let mut code = String::new();
    code.push_str(
        "use binbun_ast::ir::{Expr, ExprId};\nuse binbun_semantics::ir::{Binary, Flag, Unary};\n\n",
    );
    let mut body = String::new();
    let _ = writeln!(
        body,
        "/// The rules, in the order they are tried.\npub static RULES: [Rule; {}] = [",
        rules.len()
    );
    for rule in &rules {
        let _ = writeln!(body, "{},", data(rule));
    }
    body.push_str("];\n\n");
    let _ = writeln!(
        body,
        "/// Each rule's matcher, by index into [`RULES`].\npub(super) static MATCHERS: [Apply; {}] = [",
        rules.len()
    );
    for index in 0..rules.len() {
        let _ = writeln!(body, "rule_{index},");
    }
    body.push_str("];\n\n");
    let mut filed: Vec<(String, Vec<usize>)> = Vec::new();
    for (index, rule) in rules.iter().enumerate() {
        let lhs = &rule.parsed.lhs;
        let shape = shape(&lhs.nodes[lhs.nodes.len() - 1])
            .ok_or_else(|| format!("{}: the left side must be an operation", rule.parsed.name))?;
        match filed.iter_mut().find(|(s, _)| *s == shape) {
            Some((_, list)) => list.push(index),
            None => filed.push((shape, vec![index])),
        }
    }
    let _ = writeln!(
        body,
        "/// The rules by the kind of their left side's root.\npub(super) static DISPATCH: [(Shape, &[usize]); {}] = [",
        filed.len()
    );
    for (shape, list) in &filed {
        let list: Vec<String> = list.iter().map(usize::to_string).collect();
        let _ = writeln!(body, "({shape}, &[{}]),", list.join(", "));
    }
    body.push_str("];\n\n");
    for (index, rule) in rules.iter().enumerate() {
        body.push_str(&matcher(rule, index)?);
        body.push('\n');
    }
    // Import what the code uses: the data's types, the matchers' helpers.
    let types = [
        "Apply",
        "Constraint",
        "Literal",
        "Matcher",
        "Node",
        "Relation",
        "Rule",
        "Shape",
        "Width",
        "WidthVar",
    ];
    let helpers = [
        "bin", "claimed", "concat", "extend", "extract", "flag", "holds", "int", "select", "un",
    ];
    let mut used: Vec<&str> = types
        .into_iter()
        .filter(|name| {
            ["::", " {", ";", "<"]
                .iter()
                .any(|after| body.contains(&format!("{name}{after}")))
        })
        .collect();
    used.extend(helpers.into_iter().filter(|name| {
        body.contains(&format!("= {name}(")) || body.contains(&format!("!{name}("))
    }));
    let _ = writeln!(code, "use super::{{{}}};\n", used.join(", "));
    code.push_str(&body);
    let tokens: TokenStream = code
        .parse()
        .map_err(|e| format!("generated rules do not parse: {e}"))?;
    let mut docs = vec![
        "The rewrite rules of `crates/binbun-decompile/rules/` compiled: each".to_owned(),
        "rule as data ([`RULES`]), its matcher, and the rules filed by the kind".to_owned(),
        "of their left side's root.".to_owned(),
        String::new(),
        format!("{} rules:", rules.len()),
    ];
    let mut groups: BTreeMap<&str, usize> = BTreeMap::new();
    for rule in &rules {
        *groups.entry(rule.parsed.group.as_str()).or_insert(0) += 1;
    }
    for (group, count) in groups {
        docs.push(format!("- `{group}`: {count}"));
    }
    Ok(vec![GeneratedFile {
        path: PathBuf::from("crates/binbun-decompile/src/simplify/rules/generated.rs"),
        notice: NOTICE,
        docs,
        tokens,
    }])
}
