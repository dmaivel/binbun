/// The status flags L0 models: name in the semantics, `Flag` variant, XED
/// flag, and bits in `binbun_x86::FlagSet`. The x87 condition codes
/// count as flags: XED's flag records say which instructions change them.
const FLAGS: [(&str, &str, XedFlag, u32); 11] = [
    ("cf", "Cf", XedFlag::Cf, 1 << 0),
    ("pf", "Pf", XedFlag::Pf, 1 << 2),
    ("af", "Af", XedFlag::Af, 1 << 4),
    ("zf", "Zf", XedFlag::Zf, 1 << 6),
    ("sf", "Sf", XedFlag::Sf, 1 << 7),
    ("of", "Of", XedFlag::Of, 1 << 11),
    ("df", "Df", XedFlag::Df, 1 << 10),
    ("c0", "Fc0", XedFlag::Fc0, 1 << 28),
    ("c1", "Fc1", XedFlag::Fc1, 1 << 29),
    ("c2", "Fc2", XedFlag::Fc2, 1 << 30),
    ("c3", "Fc3", XedFlag::Fc3, 1 << 31),
];

/// The register a numbered name stands for: `zmm0`–`zmm15` and the
/// physical x87 registers `fpr0`–`fpr7`, as code for its `RegisterId`.
fn numbered(name: &str) -> Option<TokenStream> {
    let (first, count, rest) = if let Some(rest) = name.strip_prefix("zmm") {
        (quote!(ZMM0), 16, rest)
    } else {
        (quote!(FPR0), 8, name.strip_prefix("fpr")?)
    };
    let index: u16 = rest.parse().ok().filter(|&index| index < count)?;
    if rest != index.to_string() {
        return None;
    }
    Some(quote!(RegisterId(registers::#first.0 + #index)))
}

/// L0 registers the semantics name directly, with their `RegisterId`
/// constants in `crate::registers`: SSE control and status, and the x87
/// state that is not a flag (also [`numbered`] ones).
const NAMED: [(&str, &str); 5] = [
    ("mxcsr", "MXCSR"),
    ("fcw", "FCW"),
    ("fsw", "FSW"),
    ("ftop", "FTOP"),
    ("ftw", "FTW"),
];

/// The general-purpose registers the semantics may name (lower case, any
/// width, from XED's register table), with their widths in bits.
pub type Registers = BTreeMap<String, u32>;

/// What one reported operand is, for the semantics.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    /// A value the semantics see as a parameter.
    Data,
    StackPush,
    StackPop,
    /// XED's `X87PUSH`, `X87POP` and `X87POP2`.
    X87Push,
    X87Pop,
    X87Pop2,
    InstructionPointer,
    /// The flags register, stack memory and its base, segment registers:
    /// the runtime handles them.
    Implied,
}

/// A form's operands as the semantics see them.
#[derive(Clone, Debug, PartialEq, Eq)]
#[expect(
    clippy::struct_excessive_bools,
    reason = "independent facts about a form"
)]
struct Shape {
    /// Data operands: position in the decoder's operand list, and action.
    data: Vec<(usize, Action)>,
    push: bool,
    pop: bool,
    /// x87 pushes and pops.
    x87_push: bool,
    x87_pops: usize,
    writes_ip: bool,
    /// Whether a data operand is in memory.
    memory: bool,
}

fn kind(name: &str, value: &Value<'_>, width: Option<&str>) -> Kind {
    match value {
        Value::Register("XED_REG_STACKPUSH") => return Kind::StackPush,
        Value::Register("XED_REG_STACKPOP") => return Kind::StackPop,
        Value::Register("XED_REG_X87PUSH") => return Kind::X87Push,
        Value::Register("XED_REG_X87POP") => return Kind::X87Pop,
        Value::Register("XED_REG_X87POP2") => return Kind::X87Pop2,
        // The x87 status, control and tag words, last-instruction pointers:
        // the semantics name what they change.
        Value::Register(register) if register.starts_with("XED_REG_X87") => {
            return Kind::Implied;
        }
        Value::Register("XED_REG_RIP" | "XED_REG_EIP" | "XED_REG_IP") | Value::Lookup("rIP") => {
            return Kind::InstructionPointer;
        }
        Value::Register("XED_REG_FLAGS" | "XED_REG_EFLAGS" | "XED_REG_RFLAGS")
        | Value::Lookup("rFLAGS") => return Kind::Implied,
        Value::Present
        | Value::Register(_)
        | Value::Error(_)
        | Value::Enumerator(_)
        | Value::Number(_)
        | Value::Bits(_)
        | Value::Lookup(_) => {}
    }
    let data = matches!(
        name,
        "REG0"
            | "REG1"
            | "REG2"
            | "REG3"
            | "REG4"
            | "REG5"
            | "REG6"
            | "REG7"
            | "REG8"
            | "REG9"
            | "MEM0"
            | "MEM1"
            | "IMM0"
            | "IMM1"
            | "AGEN"
            | "RELBR"
            | "ABSBR"
            | "PTR"
    );
    // The stack memory operand XED adds for PUSH and POP.
    let stack_memory = name.starts_with("MEM") && width.is_some_and(|w| w.starts_with("spw"));
    if data && !stack_memory {
        Kind::Data
    } else {
        Kind::Implied
    }
}

fn shape(
    instruction: &Instruction<'_>,
    added: &[Added],
    fields: &HashMap<&str, &Field<'_>>,
    macros: &StateMacros<'_>,
) -> Result<Shape> {
    let mut shape = Shape {
        data: Vec::new(),
        push: false,
        pop: false,
        x87_push: false,
        x87_pops: 0,
        writes_ip: false,
        memory: false,
    };
    for (position, r) in reported(instruction, added, fields, macros)?
        .iter()
        .enumerate()
    {
        match kind(r.operand.name, &r.operand.value, r.operand.width) {
            Kind::Data => {
                shape.memory |= r.operand.name.starts_with("MEM");
                shape.data.push((position, r.operand.action));
            }
            Kind::StackPush => shape.push = true,
            Kind::StackPop => shape.pop = true,
            Kind::X87Push => shape.x87_push = true,
            Kind::X87Pop => shape.x87_pops = 1,
            Kind::X87Pop2 => shape.x87_pops = 2,
            Kind::InstructionPointer => {
                shape.writes_ip |=
                    !matches!(r.operand.action, Action::Read | Action::ConditionalRead);
            }
            Kind::Implied => {}
        }
    }
    Ok(shape)
}

const fn reads(action: Action) -> bool {
    !matches!(action, Action::Write)
}

const fn writes(action: Action) -> bool {
    !matches!(action, Action::Read | Action::ConditionalRead)
}

const fn always_writes(action: Action) -> bool {
    matches!(
        action,
        Action::Write | Action::ReadWrite | Action::ConditionalReadWrite
    )
}

pub fn generate(
    root: &Path,
    instructions: &[Instruction<'_>],
    added: &[Vec<Added>],
    fields: &[Field<'_>],
    macros: &StateMacros<'_>,
    registers: &Registers,
) -> Result<Vec<GeneratedFile>> {
    let (entries, helpers) = read_semantics(root, SEMANTICS, &["iclass", "iform"])?;
    let fields: HashMap<&str, &Field<'_>> = fields.iter().map(|f| (f.name, f)).collect();
    let mut by_form: BTreeMap<&str, Vec<usize>> = BTreeMap::new();
    for (index, instruction) in instructions.iter().enumerate() {
        by_form
            .entry(instruction.form.as_str())
            .or_default()
            .push(index);
    }

    // Which entry covers each form: iform entries first, then iclasses.
    let mut covered: BTreeMap<&str, usize> = BTreeMap::new();
    for (e, entry) in entries.iter().enumerate() {
        for iform in entry.keys.get(1).ok_or("iforms")? {
            let Some((&form, _)) = by_form.get_key_value(iform.as_str()) else {
                return Err(at(
                    &entry.file,
                    entry.function.sig.ident.span(),
                    format!("no form {iform}"),
                ));
            };
            if covered.insert(form, e).is_some() {
                return Err(at(
                    &entry.file,
                    entry.function.sig.ident.span(),
                    format!("{iform} covered twice"),
                ));
            }
        }
    }
    let overridden: BTreeSet<&str> = covered.keys().copied().collect();
    for (e, entry) in entries.iter().enumerate() {
        for iclass in entry.keys.first().ok_or("iclasses")? {
            let mut any = false;
            for (&form, indices) in &by_form {
                let Some(&first) = indices.first() else {
                    continue;
                };
                let record = instructions.get(first).map(|i| i.record).ok_or("form")?;
                if !record.iclass.eq_ignore_ascii_case(iclass) {
                    continue;
                }
                any = true;
                if LATER.contains(&record.extension)
                    || record.isa_set.starts_with("APX_")
                    || record.isa_set.starts_with("AVX512")
                    || record.isa_set.starts_with("AVX10")
                    || overridden.contains(form)
                {
                    continue;
                }
                if covered.insert(form, e).is_some() {
                    return Err(at(
                        &entry.file,
                        entry.function.sig.ident.span(),
                        format!("{form} covered twice"),
                    ));
                }
            }
            if !any {
                return Err(at(
                    &entry.file,
                    entry.function.sig.ident.span(),
                    format!("no iclass {iclass}"),
                ));
            }
        }
    }

    // Compile each entry once; check it against each form it covers.
    // The flags XED leaves undefined in a form are filled in by the runtime
    // where the entry does not compute them, each a site of the entry.
    let name_of = |flag: XedFlag| FLAGS.iter().find(|f| f.2 == flag).map(|f| f.0);
    let mut undefined_flags: Vec<BTreeMap<&'static str, BTreeSet<&str>>> =
        vec![BTreeMap::new(); entries.len()];
    for (&form, &e) in &covered {
        for &index in by_form.get(form).ok_or("form")? {
            let instruction = instructions.get(index).ok_or("instruction")?;
            let records = match instruction.record.flags {
                Some(text) => flags::parse(instruction.line, text)?,
                None => Vec::new(),
            };
            let undefined = records
                .iter()
                .flat_map(|record| record.actions.iter())
                .filter(|effect| effect.action == XedAction::Undefined)
                .filter_map(|effect| name_of(effect.flag));
            for flag in undefined {
                if let Some(flags) = undefined_flags.get_mut(e) {
                    flags.entry(flag).or_default().insert(form);
                }
            }
        }
    }
    let mut compiled: Vec<(TokenStream, Summary, X86<'_>)> = Vec::new();
    for (entry, flags) in entries.iter().zip(&undefined_flags) {
        let flags = flags.keys().copied().collect();
        compiled.push(compile(entry, &helpers, X86::new(registers, flags))?);
    }
    // Forms grouped by entry, operand positions, and whether they lock.
    let mut arms: BTreeMap<(usize, Vec<usize>, bool), Vec<&str>> = BTreeMap::new();
    for (&form, &e) in &covered {
        let entry = entries.get(e).ok_or("entry")?;
        let (_, summary, x86) = compiled.get(e).ok_or("entry")?;
        let indices = by_form.get(form).ok_or("form")?;
        let mut first: Option<Shape> = None;
        for &index in indices {
            let instruction = instructions.get(index).ok_or("instruction")?;
            let own = shape(
                instruction,
                added.get(index).map_or(&[][..], Vec::as_slice),
                &fields,
                macros,
            )?;
            match &first {
                Some(shape) if *shape != own => {
                    return Err(format!("{form}: patterns disagree on operands").into());
                }
                Some(_) => {}
                None => first = Some(own),
            }
            check(
                entry,
                summary,
                x86,
                form,
                first.as_ref().ok_or("shape")?,
                instruction,
            )?;
        }
        let shape = first.ok_or("form without instructions")?;
        let positions: Vec<usize> = shape.data.iter().map(|&(p, _)| p).collect();
        // A `lock` prefix (XED's `_LOCK` iclasses), and `xchg` with memory
        // (always locked), make the whole instruction one atomic access.
        let iclass = indices
            .first()
            .and_then(|&i| instructions.get(i))
            .map_or("", |i| i.record.iclass);
        let atomic = iclass.ends_with("_LOCK") || (iclass == "XCHG" && shape.memory);
        arms.entry((e, positions, atomic)).or_default().push(form);
    }

    let functions: Vec<&TokenStream> = compiled.iter().map(|(tokens, ..)| tokens).collect();
    // Imports the generated code uses.
    let text: String = functions.iter().map(ToString::to_string).collect();
    let semantic_names: Vec<Ident> = ["Binary", "FlagOp", "FloatOp", "RegisterId", "Trap", "Unary"]
        .iter()
        .filter(|name| text.contains(&format!("{name} ::")) || text.contains(&format!("{name} (")))
        .map(|name| match *name {
            "FlagOp" => format_ident!("Flag"),
            other => format_ident!("{other}"),
        })
        .collect();
    let semantic_imports = semantic_names.iter().map(|name| {
        if *name == "Flag" {
            quote!(#name as FlagOp)
        } else {
            quote!(#name)
        }
    });
    let flag = text.contains("Flag ::").then(|| quote!(Flag,));
    let register = text.contains("Register ::").then(|| quote!(Register,));
    let named = text.contains("registers ::").then(|| {
        quote!(
            use crate::registers;
        )
    });
    let sites_import = text.contains("sites ::").then(|| {
        quote!(
            use crate::sites;
        )
    });
    let arms = arms.iter().map(|((e, positions, atomic), forms)| {
        let name = entries
            .get(*e)
            .map(|entry| format_ident!("{}", entry.function.sig.ident));
        let forms = forms
            .iter()
            .map(|form| ident(form).unwrap_or_else(|_| format_ident!("INVALID")));
        let call = if positions.is_empty() {
            quote!(#name(l))
        } else {
            quote!(#name(l, [#(#positions),*]))
        };
        if *atomic {
            quote!(#(Form::#forms)|* => {
                l.b.begin_atomic();
                #call;
                l.b.end_atomic();
            })
        } else {
            quote!(#(Form::#forms)|* => { #call; })
        }
    });
    let tokens = quote! {
        use binbun_semantics::ir::{#(#semantic_imports),*};
        use binbun_x86::{#flag #register FlagSet, Form};

        use crate::lifter::Lifter;
        #named
        #sites_import

        /// Lifts an instruction of `form`; false if no semantics cover it.
        #[expect(clippy::wildcard_enum_match_arm, reason = "most forms have no semantics yet")]
        #[expect(clippy::too_many_lines, reason = "one arm per entry")]
        pub fn lift(l: &mut Lifter<'_>, form: Form) -> bool {
            match form {
                #(#arms)*
                _ => return false,
            }
            true
        }

        #(#functions)*
    };
    let mut by_entry: BTreeMap<usize, Vec<&str>> = BTreeMap::new();
    for (&form, &e) in &covered {
        by_entry.entry(e).or_default().push(form);
    }
    let sites = site_table(&entries, &compiled, &undefined_flags, &by_entry, registers)?;
    let generated = GeneratedFile {
        path: PathBuf::from("crates/binbun-x86-lift/src/generated.rs"),
        notice: NOTICE,
        docs: vec!["Semantics of each covered form, from `semantics/*.rs`.".to_owned()],
        tokens,
    };
    Ok(vec![generated, sites])
}

/// One site of the table.
struct SiteRow<'a> {
    name: String,
    output: TokenStream,
    /// Each input's name and `Input`.
    inputs: Vec<(String, TokenStream)>,
    forms: Vec<&'a str>,
}

/// `crates/binbun-x86-lift/src/sites.rs`: every entry's sites (its
/// `undefined()`s, and the flags XED leaves undefined that it does not
/// compute, which the runtime fills in), numbered in name order, with
/// their outputs, inputs and forms.
fn site_table(
    entries: &[Entry],
    compiled: &[(TokenStream, Summary, X86<'_>)],
    undefined_flags: &[BTreeMap<&'static str, BTreeSet<&str>>],
    by_entry: &BTreeMap<usize, Vec<&str>>,
    registers: &Registers,
) -> Result<GeneratedFile> {
    let mut rows: BTreeMap<String, SiteRow<'_>> = BTreeMap::new();
    for (e, (entry, (_, summary, _))) in entries.iter().zip(compiled).enumerate() {
        let entry_forms = by_entry.get(&e).cloned().unwrap_or_default();
        let mut sites: Vec<(String, String, Vec<&str>)> = summary
            .sites
            .iter()
            .map(|(name, output)| (name.clone(), output.clone(), entry_forms.clone()))
            .collect();
        if !summary.always_traps && !summary.system_call {
            for (flag, forms) in undefined_flags.get(e).into_iter().flatten() {
                if !summary.flags.contains(flag) {
                    let name = format!("{}.{flag}", entry.function.sig.ident);
                    sites.push((name, (*flag).to_owned(), forms.iter().copied().collect()));
                }
            }
        }
        // The outputs that are sites, in the order the entry makes them
        // (the flags the runtime fills in last): a site reads what the
        // entry defines for an output only if that output's site, if any,
        // comes before its own, so that no site depends on itself.
        let order: Vec<String> = sites.iter().map(|(_, output, _)| output.clone()).collect();
        for (position, (name, output, forms)) in sites.into_iter().enumerate() {
            let (output, own) = site_output(entry, &output, registers);
            let later = order.get(position..).unwrap_or_default();
            let inputs = site_inputs(entry, summary, &own, later);
            let row = SiteRow {
                name: name.clone(),
                output,
                inputs,
                forms,
            };
            if rows.insert(name.clone(), row).is_some() {
                return Err(format!("site {name} twice").into());
            }
        }
    }
    let constants: BTreeSet<String> = rows.keys().map(|n| site_constant(n).to_string()).collect();
    if constants.len() != rows.len() {
        return Err("two sites with one constant name".into());
    }
    let count = rows.len();
    let constants = rows.values().zip(0u16..).map(|(row, number)| {
        let constant = site_constant(&row.name);
        let doc = format!(" `{}`.", row.name);
        quote!(#[doc = #doc] pub const #constant: SiteId = SiteId(#number);)
    });
    let info = rows.values().map(|row| {
        let name = &row.name;
        let inputs = row.inputs.iter().map(|(name, _)| name);
        quote!(SiteInfo { name: #name, inputs: &[#(#inputs),*] })
    });
    let sites = rows.values().map(|row| {
        let output = &row.output;
        let inputs = row.inputs.iter().map(|(_, input)| input);
        let forms = row
            .forms
            .iter()
            .map(|form| ident(form).unwrap_or_else(|_| format_ident!("INVALID")));
        quote!(Site { output: #output, inputs: &[#(#inputs),*], forms: &[#(Form::#forms),*] })
    });
    let text: String = rows.values().map(|row| row.output.to_string()).collect();
    let register = text.contains("Register ::").then(|| quote!(Register,));
    let tokens = quote! {
        use binbun_semantics::ir::{SiteId, SiteInfo};
        use binbun_x86::{Flag, Form, #register};

        use crate::site::{Input, Output, Site};

        #(#constants)*

        /// Each site's name and inputs, by number: what x86 declares to L0.
        pub const INFO: [SiteInfo; #count] = [#(#info),*];

        /// Each site's output, inputs and forms (those of its entry; for a
        /// flag XED leaves undefined, those whose records say so), by
        /// number.
        pub static SITES: [Site; #count] = [#(#sites),*];
    };
    Ok(GeneratedFile {
        path: PathBuf::from("crates/binbun-x86-lift/src/sites.rs"),
        notice: NOTICE,
        docs: vec!["The sites of the semantics' undefined values (`crate::site`).".to_owned()],
        tokens,
    })
}

/// What a site's output is in the semantics.
enum Own {
    Flag(&'static str),
    Param(usize),
    Register,
    Memory,
}

/// The `Output` of a site whose value goes to `output` (a flag, parameter,
/// register, or else a part of a memory operand), and what it is.
fn site_output(entry: &Entry, output: &str, registers: &Registers) -> (TokenStream, Own) {
    if let Some((name, variant)) = flag_variant(output) {
        let variant = format_ident!("{variant}");
        (quote!(Output::Flag(Flag::#variant)), Own::Flag(name))
    } else if let Some(index) = entry.params.iter().position(|p| p == output) {
        let number = u8::try_from(index).unwrap_or(u8::MAX);
        (quote!(Output::Operand(#number)), Own::Param(index))
    } else if registers.contains_key(output) {
        let register = format_ident!("{}", output.to_ascii_uppercase());
        (quote!(Output::Register(Register::#register)), Own::Register)
    } else {
        (quote!(Output::Memory), Own::Memory)
    }
}

/// A site's inputs, named: the parameters whose values the entry reads (as
/// read), the flags it reads before writing them, `old` for a flag or
/// register output, the parameters it assigns (`defined.<name>`) and CF if
/// it computes it (`defined.cf`), unless their site is the output's own or
/// one of the `later` ones.
fn site_inputs(
    entry: &Entry,
    summary: &Summary,
    own: &Own,
    later: &[String],
) -> Vec<(String, TokenStream)> {
    let later = |name: &str| later.iter().any(|output| output == name);
    let mut inputs = Vec::new();
    for &index in &summary.values {
        let number = u8::try_from(index).unwrap_or(u8::MAX);
        let name = entry.params.get(index).cloned().unwrap_or_default();
        inputs.push((name, quote!(Input::Operand(#number))));
    }
    for (name, variant, ..) in FLAGS {
        if summary.read_flags.contains(name) && !matches!(own, Own::Flag(flag) if *flag == name) {
            let variant = format_ident!("{variant}");
            inputs.push((name.to_owned(), quote!(Input::Flag(Flag::#variant))));
        }
    }
    if matches!(own, Own::Flag(_) | Own::Register) {
        inputs.push(("old".to_owned(), quote!(Input::Old)));
    }
    for &index in &summary.whole {
        let name = entry.params.get(index).cloned().unwrap_or_default();
        if matches!(own, Own::Param(param) if *param == index) || later(&name) {
            continue;
        }
        let number = u8::try_from(index).unwrap_or(u8::MAX);
        inputs.push((format!("defined.{name}"), quote!(Input::Defined(#number))));
    }
    if summary.flags.contains("cf") && !matches!(own, Own::Flag("cf")) && !later("cf") {
        inputs.push((
            "defined.cf".to_owned(),
            quote!(Input::DefinedFlag(Flag::Cf)),
        ));
    }
    inputs
}

fn check(
    entry: &Entry,
    summary: &Summary,
    x86: &X86<'_>,
    form: &str,
    shape: &Shape,
    instruction: &Instruction<'_>,
) -> Result<()> {
    let fail = |message: String| {
        at(
            &entry.file,
            entry.function.sig.ident.span(),
            format!("{form}: {message}"),
        )
    };
    if shape.data.len() != entry.params.len() {
        return Err(fail(format!(
            "{} parameters, but the form has {} data operands",
            entry.params.len(),
            shape.data.len()
        )));
    }
    for (i, (&(_, action), name)) in shape.data.iter().zip(&entry.params).enumerate() {
        if summary.assigned.contains(&i) && !writes(action) {
            return Err(fail(format!(
                "`{name}` is assigned, but XED does not write it"
            )));
        }
        if always_writes(action) && !summary.assigned.contains(&i) {
            return Err(fail(format!(
                "XED writes `{name}`, but the entry does not assign it"
            )));
        }
        if summary.read.contains(&i) && !reads(action) {
            return Err(fail(format!("`{name}` is read, but XED only writes it")));
        }
    }
    if shape.push != x86.push {
        return Err(fail(format!(
            "XED {} the stack, the entry {}",
            if shape.push {
                "pushes on"
            } else {
                "does not push on"
            },
            if x86.push { "pushes" } else { "does not" }
        )));
    }
    if shape.pop != x86.pop {
        return Err(fail(format!(
            "XED {} the stack, the entry {}",
            if shape.pop {
                "pops from"
            } else {
                "does not pop from"
            },
            if x86.pop { "pops" } else { "does not" }
        )));
    }
    if shape.x87_push != (x86.x87_pushes > 0) || shape.x87_pops != x86.x87_pops {
        return Err(fail(format!(
            "XED pushes {} and pops {} on the x87 stack, the entry {} and {}",
            u8::from(shape.x87_push),
            shape.x87_pops,
            x86.x87_pushes,
            x86.x87_pops
        )));
    }
    // An instruction that always traps or enters the system has XED's
    // effects of the exception or system call, which the system owns.
    if summary.always_traps || summary.system_call {
        return Ok(());
    }
    if shape.writes_ip != summary.transfers {
        return Err(fail(
            "control transfers do not match XED's writes to the instruction pointer".into(),
        ));
    }
    let records = match instruction.record.flags {
        Some(text) => flags::parse(instruction.line, text)?,
        None => Vec::new(),
    };
    let name_of = |flag: XedFlag| FLAGS.iter().find(|f| f.2 == flag).map(|f| f.0);
    let unrecorded = UNRECORDED_FLAGS
        .iter()
        .filter(|(iclass, _)| instruction.record.iclass == *iclass)
        .flat_map(|(_, flags)| flags.iter().copied());
    let written: BTreeSet<&str> = records
        .iter()
        .flat_map(|r| r.actions.iter())
        .filter(|e| e.action != XedAction::Test)
        .filter_map(|e| name_of(e.flag))
        .chain(unrecorded)
        .collect();
    for flag in &summary.flags {
        if !written.contains(flag) {
            return Err(fail(format!("assigns {flag}, which XED does not write")));
        }
    }
    for record in &records {
        for effect in &record.actions {
            let Some(name) = name_of(effect.flag) else {
                if effect.action != XedAction::Test {
                    return Err(fail(format!(
                        "writes {:?}, which L0 does not model",
                        effect.flag
                    )));
                }
                continue;
            };
            let computed = summary.flags.contains(name);
            if effect.action == XedAction::Modify && !computed {
                return Err(fail(format!(
                    "XED modifies {name}, the entry does not compute it"
                )));
            }
            if effect.action == XedAction::Undefined
                && record.strength == Strength::May
                && !computed
            {
                return Err(fail(format!(
                    "XED may leave {name} undefined: say when, in the entry"
                )));
            }
        }
    }
    Ok(())
}

/// The flag's `Flag` variant name, if `name` is a modelled flag.
fn flag_variant(name: &str) -> Option<(&'static str, &'static str)> {
    FLAGS.iter().find(|f| f.0 == name).map(|f| (f.0, f.1))
}

/// Built-ins whose first argument is an operand they access themselves
/// (not its value): memory elements at explicit addresses, a gather's index
/// register, a vector register wider than its operand, parts of a memory
/// operand wider than L0's values.
const OPERAND_BUILT_INS: [&str; 8] = [
    "address",
    "vsib_address",
    "vsib_index",
    "load",
    "store",
    "wide",
    "load_part",
    "store_part",
];

/// Flags the processor writes that XED's records omit (measured): VPTEST,
/// VTESTPS and VTESTPD clear OF, AF, PF and SF, as the SDM says (XED lists
/// only ZF and CF); the instructions that load or reset the whole x87 state
/// (XED's `x87_mmx_state_w`) set the condition codes.
const UNRECORDED_FLAGS: [(&str, &[&str]); 8] = [
    ("VPTEST", &["of", "af", "pf", "sf"]),
    ("VTESTPS", &["of", "af", "pf", "sf"]),
    ("VTESTPD", &["of", "af", "pf", "sf"]),
    ("FNINIT", &["c0", "c1", "c2", "c3"]),
    ("FNSAVE", &["c0", "c1", "c2", "c3"]),
    ("FRSTOR", &["c0", "c1", "c2", "c3"]),
    ("FXRSTOR", &["c0", "c1", "c2", "c3"]),
    ("FXRSTOR64", &["c0", "c1", "c2", "c3"]),
];

/// The full register of a string pointer name: `arsi` and `ardi` are XED's
/// `ArSI()` and `ArDI()`, rsi and rdi at the address size.
fn string_register(name: &str) -> Option<Ident> {
    match name {
        "arsi" => Some(format_ident!("RSI")),
        "ardi" => Some(format_ident!("RDI")),
        _ => None,
    }
}

/// What the x86 language adds: XED's general-purpose register names (from
/// its register table), and what an entry does to the stacks.
struct X86<'a> {
    registers: &'a Registers,
    /// The flags XED leaves undefined in a form of the entry.
    undefined_flags: BTreeSet<&'static str>,
    push: bool,
    pop: bool,
    /// x87 pushes and pops (`fpush()`, `fpop()` calls).
    x87_pushes: usize,
    x87_pops: usize,
}

impl<'a> X86<'a> {
    const fn new(registers: &'a Registers, undefined_flags: BTreeSet<&'static str>) -> Self {
        Self {
            registers,
            undefined_flags,
            push: false,
            pop: false,
            x87_pushes: 0,
            x87_pops: 0,
        }
    }
}

impl Target for X86<'_> {
    const OPERAND_BUILT_INS: &'static [&'static str] = &OPERAND_BUILT_INS;
    // `probe(...)` accesses its operand without using it.
    const NOT_READING: &'static [&'static str] = &["same", "stack_index", "probe"];
    const TRAPS: &'static str = "trap(DE), trap(UD), trap(BP), trap(GP), trap(XM) or trap(MF)";
    const SITES: bool = true;

    fn reserved(name: &str) -> bool {
        flag_variant(name).is_some()
            || NAMED.iter().any(|n| n.0 == name)
            || numbered(name).is_some()
    }

    fn read(c: &mut Compiler<'_, Self>, name: &str, _span: Span) -> Result<Option<Val>> {
        match name {
            "osz" => return Ok(Some(Val::Static(quote!(l.osz())))),
            "asz" => return Ok(Some(Val::Static(quote!(l.asz())))),
            "ssz" => return Ok(Some(Val::Static(quote!(l.ssz())))),
            _ => {}
        }
        if let Some((flag, variant)) = flag_variant(name) {
            if !c.summary.flags.contains(flag) {
                c.summary.read_flags.insert(flag);
            }
            let variant = format_ident!("{variant}");
            return Ok(Some(Val::Dyn(c.emit(quote!(l.read_flag(Flag::#variant))))));
        }
        let unbound = c.lookup(name).is_none();
        if let Some(id) = numbered(name).filter(|_| unbound) {
            return Ok(Some(Val::Dyn(c.emit(quote!(l.read_register(#id))))));
        }
        if let Some(&(_, constant)) = NAMED.iter().find(|n| n.0 == name).filter(|_| unbound) {
            let constant = format_ident!("{constant}");
            return Ok(Some(Val::Dyn(
                c.emit(quote!(l.read_register(registers::#constant))),
            )));
        }
        if c.arch.registers.contains_key(name) && unbound {
            let register = format_ident!("{}", name.to_ascii_uppercase());
            return Ok(Some(Val::Dyn(
                c.emit(quote!(l.read_gpr(Register::#register))),
            )));
        }
        if let Some(register) = string_register(name).filter(|_| unbound) {
            return Ok(Some(Val::Dyn(c.emit(
                quote!(l.read_gpr(l.address_register(Register::#register))),
            ))));
        }
        Ok(None)
    }

    fn assign(c: &mut Compiler<'_, Self>, name: &str, right: &Expr) -> Result<bool> {
        if let Some((flag, variant)) = flag_variant(name) {
            let one = quote!(1u64);
            let value = c.expr(right, Some(&one))?;
            let value = c.materialize(value, &one);
            let variant = format_ident!("{variant}");
            c.out.push(quote!(l.write_flag(Flag::#variant, #value);));
            c.summary.flags.insert(flag);
            return Ok(true);
        }
        // Parameters and locals shadow register names.
        let unbound = c.lookup(name).is_none();
        let (method, register, width) = if let Some(&bits) =
            c.arch.registers.get(name).filter(|_| unbound)
        {
            let register = format_ident!("{}", name.to_ascii_uppercase());
            (
                quote!(write_gpr),
                quote!(Register::#register),
                quote!(#bits as u64),
            )
        } else if let Some(id) = numbered(name).filter(|_| unbound) {
            (
                quote!(write_register),
                id.clone(),
                quote!(l.register_width(#id)),
            )
        } else if let Some(&(_, constant)) = NAMED.iter().find(|n| n.0 == name).filter(|_| unbound)
        {
            let constant = format_ident!("{constant}");
            (
                quote!(write_register),
                quote!(registers::#constant),
                quote!(l.register_width(registers::#constant)),
            )
        } else if let Some(register) = string_register(name).filter(|_| unbound) {
            (
                quote!(write_gpr),
                quote!(l.address_register(Register::#register)),
                quote!(l.asz()),
            )
        } else {
            return Ok(false);
        };
        let value = c.expr(right, Some(&width))?;
        let value = c.materialize(value, &width);
        c.out.push(quote!(l.#method(#register, #value);));
        Ok(true)
    }

    fn call(
        c: &mut Compiler<'_, Self>,
        name: &str,
        args: &[&Expr],
        span: Span,
    ) -> Result<Option<Val>> {
        c.x86_call(name, args, span)
    }

    fn trap(kind: &str) -> Option<TokenStream> {
        Some(match kind {
            "DE" => quote!(Trap::Divide),
            "UD" => quote!(Trap::InvalidInstruction),
            "BP" => quote!(Trap::Breakpoint),
            "GP" => quote!(Trap::Protection),
            "XM" | "MF" => quote!(Trap::FloatingPoint),
            _ => return None,
        })
    }

    // XED's flag effects of an instruction that always traps or enters the
    // system are the system's (see `check`). The flags XED leaves undefined
    // that the entry does not compute are its sites `<entry>.<flag>`.
    fn finish(c: &Compiler<'_, Self>) -> Option<TokenStream> {
        let flag_bits_sum: u32 = c
            .summary
            .flags
            .iter()
            .filter_map(|name| FLAGS.iter().find(|f| f.0 == *name).map(|f| f.3))
            .fold(0, |bits, bit| bits | bit);
        let entry = c.entry();
        let sites = c
            .arch
            .undefined_flags
            .iter()
            .filter(|flag| !c.summary.flags.contains(*flag))
            .filter_map(|flag| {
                let (_, variant) = flag_variant(flag)?;
                let variant = format_ident!("{variant}");
                let site = site_constant(&format!("{entry}.{flag}"));
                Some(quote!((Flag::#variant, sites::#site)))
            });
        let positions = c.positions();
        (!c.summary.always_traps && !c.summary.system_call)
            .then(|| quote!(l.finish_flags(FlagSet(#flag_bits_sum), &[#(#sites),*], #positions);))
    }
}

impl Compiler<'_, X86<'_>> {
    /// x86's own built-ins: `None` if `name` is none of them.
    fn x86_call(&mut self, name: &str, args: &[&Expr], span: Span) -> Result<Option<Val>> {
        let file = self.file;
        let arity = |n: usize| -> Result<()> {
            if args.len() == n {
                Ok(())
            } else {
                Err(at(file, span, format!("`{name}` takes {n} arguments")))
            }
        };
        let arg = |i: usize| -> Result<&Expr> {
            args.get(i)
                .copied()
                .ok_or_else(|| at(file, span, format!("`{name}` needs argument {}", i + 1)))
        };
        let value = match name {
            // Runs the instruction again (a `rep` iteration): not a
            // transfer to XED, which writes no instruction pointer.
            "repeat" => {
                arity(0)?;
                self.effects += 1;
                self.out.push(quote!(l.repeat();));
                Ok(Val::Static(quote!(0u64)))
            }
            "pop" => {
                arity(0)?;
                self.arch.pop = true;
                self.effects += 1;
                Ok(Val::Dyn(self.emit(quote!(l.pop()))))
            }
            "push" => {
                arity(1)?;
                let value = self.expr(arg(0)?, None)?;
                let Val::Dyn(value) = value else {
                    return Err(self.error(arg(0)?.span(), "push an L0 value"));
                };
                self.arch.push = true;
                self.effects += 1;
                self.out.push(quote!(l.push(#value);));
                Ok(Val::Static(quote!(0u64)))
            }
            "st" => {
                arity(1)?;
                let Val::Static(index) = self.expr(arg(0)?, None)? else {
                    return Err(self.error(arg(0)?.span(), "an index known at lift time"));
                };
                Ok(Val::Dyn(self.emit(quote!(l.read_st(#index)))))
            }
            "set_st" => {
                arity(2)?;
                let Val::Static(index) = self.expr(arg(0)?, None)? else {
                    return Err(self.error(arg(0)?.span(), "an index known at lift time"));
                };
                let eighty = quote!(80u64);
                let value = self.expr(arg(1)?, Some(&eighty))?;
                let value = self.materialize(value, &eighty);
                self.effects += 1;
                self.out.push(quote!(l.write_st(#index, #value);));
                Ok(Val::Static(quote!(0u64)))
            }
            "fpush" | "fpop" => {
                arity(0)?;
                self.effects += 1;
                if name == "fpush" {
                    self.arch.x87_pushes += 1;
                    self.out.push(quote!(l.fpush();));
                } else {
                    self.arch.x87_pops += 1;
                    self.out.push(quote!(l.fpop();));
                }
                Ok(Val::Static(quote!(0u64)))
            }
            // `same(a, b)`: 1 at lift time if operands `a` and `b` name the
            // same vector register (a VSIB memory operand: its index).
            "same" => {
                arity(2)?;
                let a = self.operand(arg(0)?)?;
                let b = self.operand(arg(1)?)?;
                Ok(Val::Static(quote!(l.same_register(p[#a], p[#b]))))
            }
            // `wide(x, n)`: vector register operand `x`, `n` bits of its
            // register, also where XED's operand is narrower (`movhlps`
            // reads the high half of its source).
            "wide" => {
                arity(2)?;
                let index = self.operand(arg(0)?)?;
                let Val::Static(bits) = self.expr(arg(1)?, None)? else {
                    return Err(self.error(arg(1)?.span(), "a width known at lift time"));
                };
                if !self.written.contains(&index) {
                    self.summary.read.insert(index);
                }
                Ok(Val::Dyn(self.emit(quote!(l.read_wide(p[#index], #bits)))))
            }
            // `address(m)`: memory operand `m`'s address (64 bits), not
            // checked: `load` and `store` check each element's.
            "address" => {
                arity(1)?;
                let index = self.operand(arg(0)?)?;
                Ok(Val::Dyn(self.emit(quote!(l.memory_address(p[#index])))))
            }
            // `vsib_index(m)`: the index register of VSIB operand `m`.
            "vsib_index" => {
                arity(1)?;
                let index = self.operand(arg(0)?)?;
                Ok(Val::Dyn(self.emit(quote!(l.vsib_index(p[#index])))))
            }
            // `vsib_address(m, i)`: the address of the element of VSIB
            // operand `m` with index `i` (an index register element).
            "vsib_address" => {
                arity(2)?;
                let index = self.operand(arg(0)?)?;
                let Val::Dyn(element) = self.expr(arg(1)?, None)? else {
                    return Err(self.error(arg(1)?.span(), "an index as an L0 value"));
                };
                Ok(Val::Dyn(
                    self.emit(quote!(l.vsib_address(p[#index], #element))),
                ))
            }
            // `load(m, address, width)`: `width` bits at `address`, an
            // element of memory operand `m` (#GP or #SS as `m` unless
            // canonical). Masked loads and gathers access only the elements
            // they select; `maskmovdqu` checks its whole destination.
            "load" => {
                arity(3)?;
                let index = self.operand(arg(0)?)?;
                let address = self.expr(arg(1)?, Some(&quote!(64u64)))?;
                let address = self.materialize(address, &quote!(64u64));
                let Val::Static(width) = self.expr(arg(2)?, None)? else {
                    return Err(self.error(arg(2)?.span(), "a width known at lift time"));
                };
                self.effects += 1;
                Ok(Val::Dyn(self.emit(
                    quote!(l.load_at(p[#index], #address, (#width) / 8)),
                )))
            }
            // `store(m, address, value)`: `value` at `address`, an element
            // of memory operand `m` (which counts as assigned).
            "store" => {
                arity(3)?;
                let index = self.operand(arg(0)?)?;
                let address = self.expr(arg(1)?, Some(&quote!(64u64)))?;
                let address = self.materialize(address, &quote!(64u64));
                let Val::Dyn(value) = self.expr(arg(2)?, None)? else {
                    return Err(self.error(arg(2)?.span(), "store an L0 value"));
                };
                self.effects += 1;
                self.summary.assigned.insert(index);
                self.out
                    .push(quote!(l.store_at(p[#index], #address, #value);));
                Ok(Val::Static(quote!(0u64)))
            }
            // `stack_index(p)`: the `i` of an x87 register operand `st(i)`
            // (8 for any other operand), without reading it.
            "stack_index" => {
                arity(1)?;
                let index = self.operand(arg(0)?)?;
                Ok(Val::Static(quote!(l.stack_index(p[#index]))))
            }
            // `interrupt(n)`: a software interrupt to the vector immediate
            // operand `n` holds (a trap with its vector).
            "interrupt" => {
                arity(1)?;
                let index = self.operand(arg(0)?)?;
                self.effects += 1;
                self.out
                    .push(quote!(l.b.trap(Trap::Interrupt(l.vector(p[#index])));));
                self.summary.always_traps |= self.at_top_level();
                Ok(Val::Static(quote!(0u64)))
            }
            // `load_part(p, offset, bytes)` and `store_part(p, offset,
            // value)`: part of a memory operand wider than L0's values (an
            // x87 environment or FXSAVE image), at a byte offset known at
            // lift time.
            "load_part" => {
                arity(3)?;
                let index = self.operand(arg(0)?)?;
                let (Val::Static(offset), Val::Static(bytes)) =
                    (self.expr(arg(1)?, None)?, self.expr(arg(2)?, None)?)
                else {
                    return Err(self.error(span, "the offset and size are known at lift time"));
                };
                self.summary.read.insert(index);
                self.effects += 1;
                Ok(Val::Dyn(
                    self.emit(quote!(l.load_part(p[#index], #offset, #bytes))),
                ))
            }
            "store_part" => {
                arity(3)?;
                let index = self.operand(arg(0)?)?;
                let Val::Static(offset) = self.expr(arg(1)?, None)? else {
                    return Err(self.error(arg(1)?.span(), "an offset known at lift time"));
                };
                let Val::Dyn(value) = self.expr(arg(2)?, None)? else {
                    return Err(self.error(arg(2)?.span(), "store an L0 value"));
                };
                self.summary.assigned.insert(index);
                self.effects += 1;
                self.out
                    .push(quote!(l.store_part(p[#index], #offset, #value);));
                Ok(Val::Static(quote!(0u64)))
            }
            // `probe(p)`: memory operand p accessed and the value dropped,
            // as the processor does for a store it then skips.
            "probe" => {
                arity(1)?;
                let index = self.operand(arg(0)?)?;
                self.effects += 1;
                self.out.push(quote!(l.probe(p[#index]);));
                Ok(Val::Static(quote!(0u64)))
            }
            _ => return Ok(None),
        };
        value.map(Some)
    }
}
