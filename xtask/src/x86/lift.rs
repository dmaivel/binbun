//! `crates/binbun-x86-lift/src/generated.rs`: the hand-written semantics in
//! `crates/binbun-x86-lift/semantics/*.rs`, checked against XED's operands
//! and flags for every form they cover, compiled into Rust that drives the
//! lift runtime (`binbun_x86_lift::Lifter`).
//!
//! The semantics language is a strict subset of Rust syntax, never compiled
//! as Rust.
//! Entries are `fn`s with `#[iclass(...)]` (every form of those iclasses)
//! or `#[iform(...)]` (those forms, overriding an iclass entry); other
//! `fn`s are helpers, inlined where called.
//! The front end and compiler are shared with AArch64 (`crate::lift`);
//! here are x86's names, built-ins and the checks against XED.

