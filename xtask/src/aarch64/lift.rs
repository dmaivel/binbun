//! `crates/binbun-aarch64-lift/src/generated.rs`: the hand-written semantics
//! in `crates/binbun-aarch64-lift/semantics/*.rs`, one entry per AARCHMRS
//! operation (`#[operation(...)]`, every encoding with that
//! `operation_id`), compiled by the shared front end (`crate::lift`) into
//! Rust that drives the lift runtime (`binbun_aarch64_lift::Lifter`).
//!
//! Each entry is checked against the decoder, as x86's are against XED's
//! operand records: for sampled words of every encoding it covers (random
//! values of the encoding's free bits), the words' own-syntax operands
//! (`Instruction::encoding_operands`) must match the entry's parameters
//! (a shift written after an operand belongs to it), every operand the
//! decoder says is written must be assigned, no read-only operand may be,
//! no written-only operand read; the flags assigned must be those
//! `Instruction::flags` says are written (a flag assigned only inside an
//! `if` decided at lift time may be written or not: `rmif`'s mask, or
//! which register `msr` writes, says);
//! registers the entry names must
//! be the decoder's implicit ones (`x30` of `bl`); and the entry transfers
//! control exactly where `Instruction::flow` says the word does. The check
//! uses the checked-in decoder that xtask is built with: after changing the
//! decoder's access rules, run `cargo xtask codegen` twice.

