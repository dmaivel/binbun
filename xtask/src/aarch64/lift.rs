/// The condition flags: name in the semantics, `registers` constant, and
/// bit in `binbun_aarch64::FlagSet`.
const FLAGS: [(&str, &str, u8); 4] = [("N", "N", 8), ("Z", "Z", 4), ("C", "C", 2), ("V", "V", 1)];

/// Other state the semantics name: name, `registers` constant, width.
const NAMED: [(&str, &str, u64); 8] = [
    ("btype", "BTYPE", 2),
    ("fpcr", "FPCR", 32),
    ("fpsr", "FPSR", 32),
    ("tpidr_el0", "TPIDR_EL0", 64),
    ("tpidrro_el0", "TPIDRRO_EL0", 64),
    ("dit", "DIT", 1),
    ("ssbs", "SSBS", 1),
    ("tco", "TCO", 1),
];

/// Optional register operands the syntax omits at their default value:
/// encoding, parameter position, and the low bit of the 5-bit register
/// field (which holds the default: `ret` is `ret x30`). The runtime puts
/// `x`*field* back as the parameter; the check requires the decoder to list
/// it as an implicit read wherever it is omitted, unless it is the zero
/// register, which is no state (`irg x0, x1` is `irg x0, x1, xzr`; SYS
/// omits `xzr`: `ic iallu`).
const OMITTED: [(&str, usize, u32); 3] = [
    ("RET_64R_branch_reg", 0, 5),
    ("IRG_64I_dp_2src", 2, 16),
    ("SYS_CR_systeminstrs", 4, 0),
];

/// Words sampled per encoding (besides those with every free bit 0 or 1).
const SAMPLES: u32 = 4096;

/// The address words are decoded at (labels, `flow`).
const ADDRESS: u64 = 0x40_1000;

/// The flag's `registers` constant, if `name` is a condition flag.
fn flag(name: &str) -> Option<(&'static str, &'static str)> {
    FLAGS.iter().find(|f| f.0 == name).map(|f| (f.0, f.1))
}

/// The `registers` constant and width of named state `name`.
fn named_state(name: &str) -> Option<(&'static str, u64)> {
    NAMED.iter().find(|r| r.0 == name).map(|r| (r.1, r.2))
}

/// The register a name stands for: `x0`–`x30` as their number, `sp` as 31.
fn general(name: &str) -> Option<u8> {
    if name == "sp" {
        return Some(31);
    }
    let digits = name.strip_prefix('x')?;
    let number: u8 = digits.parse().ok().filter(|&n| n < 31)?;
    (digits == number.to_string()).then_some(number)
}

/// The `RegisterId` code of register `number` (31: the stack pointer).
fn register_id(number: u8) -> TokenStream {
    if number == 31 {
        quote!(registers::SP)
    } else {
        quote!(registers::x(#number))
    }
}

/// What the AArch64 language adds: which parameters are values known when
/// lifting, and the registers an entry names.
#[derive(Debug, Default)]
struct A64 {
    /// Per parameter: whether it is an immediate or a label.
    lift_time: Vec<bool>,
    /// Encoding fields at the same bits in every encoding the entry covers,
    /// by name: lowest bit and width.
    fields: BTreeMap<String, (u32, u32)>,
    /// General registers read and written by name (31: `sp`).
    named_reads: BTreeSet<u8>,
    named_writes: BTreeSet<u8>,
    /// Flags assigned only inside `if`s decided at lift time: written by
    /// some words of the entry, not all (`rmif`'s mask; `msr nzcv`, not
    /// `msr fpcr`).
    conditional_flags: BTreeSet<&'static str>,
}

impl Target for A64 {
    const OPERAND_BUILT_INS: &'static [&'static str] = &[
        "load",
        "store",
        "address",
        "check_alignment",
        "whole",
        "write_whole",
    ];
    const NOT_READING: &'static [&'static str] = &["field"];
    const TRAPS: &'static str = "trap(UNDEFINED), trap(BRK), trap(SP_ALIGNMENT), \
                                 trap(AUTHENTICATION) or trap(ALIGNMENT)";

    fn reserved(name: &str) -> bool {
        flag(name).is_some() || general(name).is_some() || named_state(name).is_some()
    }

    fn parameter(c: &mut Compiler<'_, Self>, index: usize) -> Option<Val> {
        if c.arch.lift_time.get(index) != Some(&true) {
            return None;
        }
        let value = c.emit(quote!(l.immediate(p[#index])));
        Some(Val::Static(quote!(#value)))
    }

    fn read(c: &mut Compiler<'_, Self>, name: &str, _span: Span) -> Result<Option<Val>> {
        if let Some((_, constant)) = flag(name) {
            let constant = format_ident!("{constant}");
            return Ok(Some(Val::Dyn(
                c.emit(quote!(l.read_register(registers::#constant))),
            )));
        }
        if let Some(number) = general(name).filter(|_| c.lookup(name).is_none()) {
            c.arch.named_reads.insert(number);
            let id = register_id(number);
            return Ok(Some(Val::Dyn(c.emit(quote!(l.read_register(#id))))));
        }
        if let Some((constant, _)) = named_state(name) {
            let constant = format_ident!("{constant}");
            return Ok(Some(Val::Dyn(
                c.emit(quote!(l.read_register(registers::#constant))),
            )));
        }
        Ok(None)
    }

    fn assign(c: &mut Compiler<'_, Self>, name: &str, right: &Expr) -> Result<bool> {
        let (id, width) = if let Some((name, constant)) = flag(name) {
            if c.lift_time_ifs > 0 {
                c.arch.conditional_flags.insert(name);
            } else {
                c.summary.flags.insert(name);
            }
            let constant = format_ident!("{constant}");
            (quote!(registers::#constant), quote!(1u64))
        } else if let Some(number) = general(name).filter(|_| c.lookup(name).is_none()) {
            c.arch.named_writes.insert(number);
            (register_id(number), quote!(64u64))
        } else if let Some((constant, width)) = named_state(name) {
            let constant = format_ident!("{constant}");
            (quote!(registers::#constant), quote!(#width))
        } else {
            return Ok(false);
        };
        let value = c.expr(right, Some(&width))?;
        let value = c.materialize(value, &width);
        c.out.push(quote!(l.write_register(#id, #value);));
        Ok(true)
    }

    /// `load(m, offset, bits)`: `bits` bits at byte `offset` of memory
    /// operand `m`; `store(m, offset, value)`: `value` there. Both known
    /// at lift time but the value: the two registers of a pair are two
    /// accesses, as Arm's pseudocode makes them without `FEAT_LSE2`. A
    /// label as `m` is the address a literal load reads.
    ///
    /// `address(m)`: the address of memory operand `m` (64 bits), for
    /// intrinsics; `check_alignment(m)`: the alignment fault of an access
    /// that must be single-copy atomic (acquire/release, exclusive,
    /// atomic), if `m` crosses an aligned 16-byte block. `field(name)`: the
    /// value of the encoding field `name` (lift time), which must lie at the
    /// same bits in every encoding the entry covers; `field(lsb, width)`:
    /// bits of the instruction word, known at lift time (fields no operand
    /// gives and AARCHMRS does not name alike in every encoding: `movk`'s
    /// `hw`, `crc32`'s `sz`, a barrier's option, a `PSTATE` field's `op1`
    /// and `op2`). `holds(n, z, c, v)`: whether the instruction's condition
    /// holds for those flag values (a compare-and-branch's). `unlifted()`:
    /// no semantics for this word yet (the lift fails as unsupported).
    /// `write_memory(address, value)`: `value` at `address`, for system
    /// instructions that write memory without a memory operand (DC ZVA).
    /// `whole(op)`: the whole `v` register (128 bits) of SIMD and
    /// floating-point register operand `op`, read as state, not as the
    /// operand; `write_whole(op, value)`: `value` (128 bits) to it, which
    /// assigns `op` (a scalar result merged into a register as FPCR.NEP
    /// says).
    fn call(
        c: &mut Compiler<'_, Self>,
        name: &str,
        args: &[&Expr],
        span: Span,
    ) -> Result<Option<Val>> {
        match (name, args) {
            ("address", [operand]) => {
                let index = c.operand(operand)?;
                return Ok(Some(Val::Dyn(c.emit(quote!(l.address(p[#index]))))));
            }
            ("check_alignment", [operand]) => {
                let index = c.operand(operand)?;
                c.effects += 1;
                c.out.push(quote!(l.check_alignment(p[#index]);));
                return Ok(Some(Val::Static(quote!(0u64))));
            }
            ("field", [Expr::Path(path)]) => {
                let field = path
                    .path
                    .get_ident()
                    .map(ToString::to_string)
                    .unwrap_or_default();
                let Some(&(lsb, width)) = c.arch.fields.get(&field) else {
                    return Err(c.error(
                        span,
                        format!("no field `{field}` at the same bits in every encoding covered"),
                    ));
                };
                let (lsb, width) = (u64::from(lsb), u64::from(width));
                return Ok(Some(Val::Static(quote!(l.field(#lsb, #width)))));
            }
            ("field", [lsb, width]) => {
                let (Val::Static(lsb), Val::Static(width)) =
                    (c.expr(lsb, None)?, c.expr(width, None)?)
                else {
                    return Err(c.error(span, "a field's place is known at lift time"));
                };
                return Ok(Some(Val::Static(quote!(l.field(#lsb, #width)))));
            }
            ("field", _) => {
                return Err(c.error(span, "`field` takes a field name, or a lsb and a width"));
            }
            ("address" | "check_alignment", _) => {
                return Err(c.error(span, format!("`{name}` takes 1 argument")));
            }
            ("whole", [operand]) => {
                let index = c.operand(operand)?;
                return Ok(Some(Val::Dyn(c.emit(quote!(l.whole(p[#index]))))));
            }
            ("write_whole", [operand, value]) => {
                let index = c.operand(operand)?;
                let Val::Dyn(value) = c.expr(value, None)? else {
                    return Err(c.error(span, "write an L0 value"));
                };
                c.summary.assigned.insert(index);
                c.out.push(quote!(l.write_whole(p[#index], #value);));
                return Ok(Some(Val::Static(quote!(0u64))));
            }
            ("whole" | "write_whole", _) => {
                return Err(c.error(span, format!("wrong arguments to `{name}`")));
            }
            ("holds", _) => {
                let [n, z, flag_c, v] = args else {
                    return Err(c.error(span, "`holds` takes 4 arguments"));
                };
                let mut flags = Vec::new();
                for arg in [n, z, flag_c, v] {
                    let value = c.expr(arg, Some(&quote!(1u64)))?;
                    flags.push(c.materialize(value, &quote!(1u64)));
                }
                return Ok(Some(Val::Dyn(c.emit(quote!(l.holds([#(#flags),*]))))));
            }
            ("unlifted", _) => {
                if !args.is_empty() {
                    return Err(c.error(span, "`unlifted` takes no arguments"));
                }
                c.out.push(quote!(l.unlifted();));
                return Ok(Some(Val::Static(quote!(0u64))));
            }
            ("write_memory", _) => {
                let [address, value] = args else {
                    return Err(c.error(span, "`write_memory` takes 2 arguments"));
                };
                let address = c.expr(address, Some(&quote!(64u64)))?;
                let address = c.materialize(address, &quote!(64u64));
                let Val::Dyn(value) = c.expr(value, None)? else {
                    return Err(c.error(span, "write an L0 value"));
                };
                c.effects += 1;
                c.out.push(quote!(l.b.store(#address, #value);));
                return Ok(Some(Val::Static(quote!(0u64))));
            }
            _ => {}
        }
        if !matches!(name, "load" | "store") {
            return Ok(None);
        }
        let [operand, offset, last] = args else {
            return Err(c.error(span, format!("`{name}` takes 3 arguments")));
        };
        let index = c.operand(operand)?;
        let Val::Static(offset) = c.expr(offset, None)? else {
            return Err(c.error(offset.span(), "an offset known at lift time"));
        };
        c.effects += 1;
        if name == "load" {
            let Val::Static(bits) = c.expr(last, None)? else {
                return Err(c.error(last.span(), "a width known at lift time"));
            };
            if !c.written.contains(&index) {
                c.summary.read.insert(index);
            }
            return Ok(Some(Val::Dyn(
                c.emit(quote!(l.load_at(p[#index], #offset, (#bits) / 8))),
            )));
        }
        let Val::Dyn(value) = c.expr(last, None)? else {
            return Err(c.error(last.span(), "store an L0 value"));
        };
        c.summary.assigned.insert(index);
        c.out.push(quote!(l.store_at(p[#index], #offset, #value);));
        Ok(Some(Val::Static(quote!(0u64))))
    }

    fn trap(kind: &str) -> Option<TokenStream> {
        Some(match kind {
            "UNDEFINED" => quote!(Trap::InvalidInstruction),
            "BRK" => quote!(Trap::Breakpoint),
            "SP_ALIGNMENT" => quote!(Trap::Stack),
            "AUTHENTICATION" => quote!(Trap::Authentication),
            "ALIGNMENT" => quote!(Trap::Alignment),
            _ => return None,
        })
    }

    // The writeback and BTYPE of an instruction that always traps or enters
    // the system do not happen.
    fn finish(c: &Compiler<'_, Self>) -> Option<TokenStream> {
        (!c.summary.always_traps && !c.summary.system_call).then(|| quote!(l.complete();))
    }
}

/// What a parameter is.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Kind {
    Register(RegisterClass),
    Memory,
    /// An immediate, a label, a system register or a SYS `C` register: a
    /// value known when lifting.
    Value,
}

/// A word's parameters as the semantics see them, with the decoder's
/// access of each.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Shape {
    params: Vec<(Kind, Access)>,
}

/// The parameters of `instruction` (as the runtime builds them), or why it
/// has none the runtime can lift.
fn shape(instruction: Instruction, omitted: Omitted) -> Result<Shape, String> {
    let operands = instruction.encoding_operands();
    let accesses = instruction.encoding_access();
    let mut params = Vec::new();
    for (operand, &access) in operands.as_slice().iter().zip(accesses.as_slice()) {
        let kind = match operand {
            // Shifts and extensions belong to the operand before them; the
            // condition is `cond()`.
            Operand::Shift(_) | Operand::Extend(_) | Operand::Condition(_) => continue,
            Operand::Register(register) if register.class == RegisterClass::C => Kind::Value,
            Operand::Register(register) => Kind::Register(register.class),
            Operand::Memory(_) => Kind::Memory,
            // A name (`pldl1keep`, a barrier option, a `PSTATE` field) is
            // known when lifting; where the field has no name it is written
            // as an immediate. Where the syntax shows a name only sometimes
            // (`bti` and `bti c`), the entry takes no parameters and reads
            // the word's fields. A floating-point immediate (`fmov d0,
            // #1.0`) is known when lifting too: the entry builds it from the
            // word's `imm8` field (Arm's `VFPExpandImm`).
            Operand::Immediate(_)
            | Operand::Label(_)
            | Operand::SystemRegister(_)
            | Operand::Named(_)
            | Operand::Float(_) => Kind::Value,
            other @ (Operand::List(_)
            | Operand::Writeback(_)
            | Operand::Za(_)
            | Operand::ZaList(_)
            | Operand::TableSlice(_)
            | Operand::IndexedRegister(_)) => {
                return Err(format!("operand {other:?} is not lifted yet"));
            }
        };
        params.push((kind, access));
    }
    if let Some((position, lsb)) = omitted {
        let number = u8::try_from((instruction.word() >> lsb) & 31).unwrap_or(31);
        let default = Register::new(RegisterClass::X, number);
        if params.len() <= position {
            if !default.is_zero() && !instruction.implicit().reads.contains(&default) {
                return Err(format!(
                    "the omitted operand is not the implicit {default:?}"
                ));
            }
            params.insert(position, (Kind::Register(RegisterClass::X), Access::Read));
        }
    }
    Ok(Shape { params })
}

/// Sampled words of `encoding` that decode as it.
fn words(encoding: &Encoding<'_>) -> Vec<Instruction> {
    let free = !encoding.fixed.mask;
    let mut state = 0x9e37_79b9_7f4a_7c15_u64 ^ u64::from(encoding.fixed.value);
    let mut candidates = vec![encoding.fixed.value, encoding.fixed.value | free];
    for _ in 0..SAMPLES {
        state ^= state << 13;
        state ^= state >> 7;
        state ^= state << 17;
        let random = u32::try_from(state >> 32).unwrap_or(0);
        candidates.push(encoding.fixed.value | (random & free));
    }
    candidates
        .into_iter()
        .filter_map(|word| decode(word).ok())
        .filter(|instruction| instruction.encoding().name() == encoding.name())
        .collect()
}

/// The register a decoder `Register` is, by number, if it is a general one
/// the semantics can name.
fn named(register: Register) -> Option<u8> {
    match register.class {
        RegisterClass::X | RegisterClass::W => Some(register.number),
        RegisterClass::Xsp | RegisterClass::Wsp => Some(31),
        RegisterClass::B
        | RegisterClass::H
        | RegisterClass::S
        | RegisterClass::D
        | RegisterClass::Q
        | RegisterClass::V
        | RegisterClass::Z
        | RegisterClass::P
        | RegisterClass::Pn
        | RegisterClass::Zt
        | RegisterClass::C
        | RegisterClass::Ffr => None,
    }
}

/// Checks a compiled entry against one word.
fn check(
    entry: &Entry,
    summary: &Summary,
    arch: &A64,
    shape: &Shape,
    instruction: Instruction,
) -> Result<()> {
    let fail = |message: String| {
        at(
            &entry.file,
            entry.function.sig.ident.span(),
            format!(
                "{} ({:#010x}): {message}",
                instruction.encoding().name(),
                instruction.word()
            ),
        )
    };
    // An entry without parameters may take its fields from the word when
    // the syntax's operands are all values or the zero register (`dmb ish`
    // and `dmb #0`; `msr S0_7_C4_C15_7, xzr`).
    let fields_only = entry.params.is_empty()
        && instruction
            .encoding_operands()
            .as_slice()
            .iter()
            .all(|operand| match operand {
                Operand::Register(register) => {
                    register.class == RegisterClass::C || register.is_zero()
                }
                Operand::Immediate(_)
                | Operand::Label(_)
                | Operand::SystemRegister(_)
                | Operand::Named(_) => true,
                Operand::List(_)
                | Operand::Float(_)
                | Operand::Shift(_)
                | Operand::Extend(_)
                | Operand::Memory(_)
                | Operand::Writeback(_)
                | Operand::Condition(_)
                | Operand::Za(_)
                | Operand::ZaList(_)
                | Operand::TableSlice(_)
                | Operand::IndexedRegister(_) => false,
            });
    if shape.params.len() != entry.params.len() && !fields_only {
        return Err(fail(format!(
            "{} parameters, but the word has {} operands",
            entry.params.len(),
            shape.params.len()
        )));
    }
    for (i, (&(kind, access), name)) in shape.params.iter().zip(&entry.params).enumerate() {
        // A value known when lifting is part of the syntax: a system
        // register the decoder says is written is the entry's to write (by
        // name), never the parameter.
        if kind == Kind::Value {
            if summary.assigned.contains(&i) {
                return Err(fail(format!(
                    "`{name}` is part of the syntax: not assignable"
                )));
            }
            continue;
        }
        if summary.assigned.contains(&i) && !access.writes() {
            return Err(fail(format!(
                "`{name}` is assigned, but the decoder says it is only read"
            )));
        }
        if access.writes() && !summary.assigned.contains(&i) {
            return Err(fail(format!(
                "the decoder says `{name}` is written, but the entry does not assign it"
            )));
        }
        if summary.read.contains(&i) && !access.reads() {
            return Err(fail(format!(
                "`{name}` is read, but the decoder says it is only written"
            )));
        }
        if kind == Kind::Memory
            && !matches!(
                instruction.memory().map(|memory| memory.kind),
                Some(
                    MemoryKind::Load
                        | MemoryKind::Store
                        | MemoryKind::Atomic
                        | MemoryKind::LoadExclusive
                        | MemoryKind::StoreExclusive
                        | MemoryKind::Prefetch
                )
            )
        {
            return Err(fail(format!(
                "`{name}`: only loads, stores, atomics and prefetches are lifted yet"
            )));
        }
    }
    let bits = |names: &BTreeSet<&str>| -> u8 {
        names
            .iter()
            .filter_map(|name| FLAGS.iter().find(|f| f.0 == *name).map(|f| f.2))
            .fold(0, |bits, bit| bits | bit)
    };
    // Flags assigned in a lift-time `if` may be written by this word.
    let written = bits(&summary.flags);
    let conditional = bits(&arch.conditional_flags);
    let decoder = instruction.flags().written.bits();
    if !summary.always_traps && (written & !decoder != 0 || decoder & !(written | conditional) != 0)
    {
        return Err(fail(format!(
            "assigns flags {written:#06b} (and {conditional:#06b} at lift time), the decoder \
             says {decoder:#06b} are written"
        )));
    }
    let implicit = instruction.implicit();
    let implicit_writes: BTreeSet<u8> = implicit.writes.iter().copied().filter_map(named).collect();
    if !summary.always_traps && arch.named_writes != implicit_writes {
        return Err(fail(format!(
            "writes registers {:?} by name, the decoder's implicit writes are {:?}",
            arch.named_writes, implicit.writes
        )));
    }
    let implicit_reads: BTreeSet<u8> = implicit.reads.iter().copied().filter_map(named).collect();
    if !arch.named_reads.is_subset(&implicit_reads) {
        return Err(fail(format!(
            "reads registers {:?} by name, the decoder's implicit reads are {:?}",
            arch.named_reads, implicit.reads
        )));
    }
    let transfers = instruction.flow(ADDRESS) != Flow::Next;
    if !summary.always_traps && !summary.system_call && transfers != summary.transfers {
        return Err(fail(format!(
            "the decoder's flow is {:?}, the entry {} control",
            instruction.flow(ADDRESS),
            if summary.transfers {
                "transfers"
            } else {
                "does not transfer"
            }
        )));
    }
    Ok(())
}

/// Where the runtime restores an omitted operand: its parameter position
/// and the low bit of its register field ([`OMITTED`]).
type Omitted = Option<(usize, u32)>;

/// One covered encoding: its entry, and sampled words with their shapes.
struct Covered<'a> {
    entry: usize,
    words: Vec<(Instruction, Shape)>,
    omitted: Omitted,
    /// An atomic read-modify-write (the decoder's `MemoryKind::Atomic`):
    /// the entry runs as one indivisible access.
    atomic: bool,
    /// The encoding's named fields: name, lowest bit, width.
    fields: Vec<(&'a str, u32, u32)>,
    name: &'a str,
}

/// The encodings each entry covers, with sampled words. An
/// `#[operation(...)]` entry covers every encoding of its operations but
/// those an `#[encoding(...)]` entry names (encodings of one operation whose
/// syntax differs: `pacia x1, x2`, `paciza x1`, `paciasp`).
fn cover<'a>(entries: &[Entry], encodings: &'a [Encoding<'a>]) -> Result<Vec<Covered<'a>>> {
    let mut by_operation: BTreeMap<&str, Vec<&Encoding<'_>>> = BTreeMap::new();
    for encoding in encodings {
        by_operation
            .entry(encoding.instruction.operation_id.as_str())
            .or_default()
            .push(encoding);
    }
    let mut claimed: BTreeMap<&str, usize> = BTreeMap::new();
    for (e, entry) in entries.iter().enumerate() {
        let fail = |message: String| at(&entry.file, entry.function.sig.ident.span(), message);
        let [operations, names] = entry.keys.as_slice() else {
            return Err(fail("operation and encoding keys".into()));
        };
        if !operations.is_empty() && !names.is_empty() {
            return Err(fail(
                "an entry covers operations or encodings, not both".into(),
            ));
        }
        for name in names {
            let Some(encoding) = encodings.iter().find(|encoding| encoding.name() == name) else {
                return Err(fail(format!("no encoding {name}")));
            };
            if claimed.insert(encoding.name(), e).is_some() {
                return Err(fail(format!("{name} covered twice")));
            }
        }
    }
    let mut covered = Vec::new();
    let mut seen = BTreeSet::new();
    for (e, entry) in entries.iter().enumerate() {
        let fail = |message: String| at(&entry.file, entry.function.sig.ident.span(), message);
        let mut members: Vec<&Encoding<'_>> = Vec::new();
        for operation in entry.keys.first().ok_or("operations")? {
            let Some(operation_members) = by_operation.get(operation.as_str()) else {
                return Err(fail(format!("no operation {operation}")));
            };
            if !seen.insert(operation.clone()) {
                return Err(fail(format!("{operation} covered twice")));
            }
            members.extend(
                operation_members
                    .iter()
                    .copied()
                    .filter(|encoding| !claimed.contains_key(encoding.name())),
            );
        }
        members.extend(
            encodings
                .iter()
                .filter(|encoding| claimed.get(encoding.name()) == Some(&e)),
        );
        if members.is_empty() {
            return Err(fail("the entry covers no encoding".into()));
        }
        for encoding in members {
            let omitted = OMITTED
                .iter()
                .find(|o| o.0 == encoding.name())
                .map(|o| (o.1, o.2));
            let mut sampled = Vec::new();
            for instruction in words(encoding) {
                let shape = shape(instruction, omitted).map_err(|message| {
                    fail(format!(
                        "{} ({:#010x}): {message}",
                        encoding.name(),
                        instruction.word()
                    ))
                })?;
                sampled.push((instruction, shape));
            }
            if sampled.is_empty() {
                return Err(fail(format!(
                    "no sampled word decodes as {}",
                    encoding.name()
                )));
            }
            let atomic = |instruction: &Instruction| {
                instruction.memory().map(|memory| memory.kind) == Some(MemoryKind::Atomic)
            };
            let first = sampled
                .first()
                .is_some_and(|(instruction, _)| atomic(instruction));
            if sampled
                .iter()
                .any(|(instruction, _)| atomic(instruction) != first)
            {
                return Err(fail(format!(
                    "{}: atomic in some words and not in others",
                    encoding.name()
                )));
            }
            let fields = encoding
                .instruction
                .encoding
                .fields
                .iter()
                .filter_map(|f| Some((f.name.as_deref()?, f.start, f.width)))
                .collect();
            covered.push(Covered {
                entry: e,
                words: sampled,
                omitted,
                atomic: first,
                fields,
                name: encoding.name(),
            });
        }
    }
    Ok(covered)
}

/// Which parameters of entry `e` are values known when lifting, the same
/// in every word it covers.
fn lift_time(entry: &Entry, e: usize, covered: &[Covered<'_>]) -> Result<Vec<bool>> {
    if entry.params.is_empty() {
        return Ok(Vec::new());
    }
    let mut kinds: Option<Vec<bool>> = None;
    for (instruction, shape) in covered
        .iter()
        .filter(|c| c.entry == e)
        .flat_map(|c| &c.words)
    {
        // Unused parameters (`_name`) are never read, whatever they are.
        let own: Vec<bool> = shape
            .params
            .iter()
            .zip(&entry.params)
            .map(|(p, name)| p.0 == Kind::Value && !name.starts_with('_'))
            .collect();
        match &kinds {
            Some(kinds) if *kinds != own => {
                return Err(at(
                    &entry.file,
                    entry.function.sig.ident.span(),
                    format!(
                        "{:#010x}: an operand is a value in some words and not in others",
                        instruction.word()
                    ),
                ));
            }
            Some(_) => {}
            None => kinds = Some(own),
        }
    }
    Ok(kinds.unwrap_or_default())
}

/// The fields at the same bits in every encoding entry `e` covers.
fn common_fields(e: usize, covered: &[Covered<'_>]) -> BTreeMap<String, (u32, u32)> {
    let mut encodings = covered.iter().filter(|c| c.entry == e);
    let Some(first) = encodings.next() else {
        return BTreeMap::new();
    };
    let mut fields: BTreeMap<String, (u32, u32)> = first
        .fields
        .iter()
        .map(|&(name, lsb, width)| (name.to_owned(), (lsb, width)))
        .collect();
    for c in encodings {
        fields.retain(|name, &mut (lsb, width)| {
            c.fields
                .iter()
                .any(|f| f.0 == name.as_str() && f.1 == lsb && f.2 == width)
        });
    }
    fields
}

pub fn generate(root: &Path, encodings: &[Encoding<'_>]) -> Result<GeneratedFile> {
    let (entries, helpers) = read_semantics(root, SEMANTICS, &["operation", "encoding"])?;
    let covered = cover(&entries, encodings)?;

    // Compile each entry once; check it against every sampled word.
    let mut functions = Vec::new();
    for (e, entry) in entries.iter().enumerate() {
        let arch = A64 {
            lift_time: lift_time(entry, e, &covered)?,
            fields: common_fields(e, &covered),
            ..A64::default()
        };
        let (tokens, summary, arch) = compile(entry, &helpers, arch)?;
        for (instruction, shape) in covered
            .iter()
            .filter(|c| c.entry == e)
            .flat_map(|c| &c.words)
        {
            check(entry, &summary, &arch, shape, *instruction)?;
        }
        functions.push(tokens);
    }

    // Encodings grouped by entry, restored operand and atomicity.
    let mut arms: BTreeMap<(usize, Omitted, bool), Vec<&str>> = BTreeMap::new();
    for c in &covered {
        arms.entry((c.entry, c.omitted, c.atomic))
            .or_default()
            .push(c.name);
    }
    let arms = arms
        .iter()
        .map(|(&(e, omitted, atomic), names)| {
            let entry = entries.get(e).ok_or("entry")?;
            let name = &entry.function.sig.ident;
            let count = entry.params.len();
            let positions = 0..count;
            let call = if count == 0 {
                quote!(#name(l))
            } else {
                quote!(#name(l, [#(#positions),*]))
            };
            // An atomic read-modify-write is one indivisible access.
            let call = if atomic {
                quote!(l.b.begin_atomic(); #call; l.b.end_atomic())
            } else {
                call
            };
            let restore =
                omitted.map(|(position, lsb)| quote!(l.restore(#count, #position, #lsb);));
            let variants = names
                .iter()
                .map(|name| encoding_ident(name))
                .collect::<Result<Vec<_>>>()?;
            Ok(quote!(#(Encoding::#variants)|* => { #restore #call; }))
        })
        .collect::<Result<Vec<_>>>()?;

    // Every covered encoding, by name.
    let mut supported: Vec<&str> = covered.iter().map(|c| c.name).collect();
    supported.sort_unstable();
    let supported_count = supported.len();
    let supported = supported
        .iter()
        .map(|name| encoding_ident(name))
        .collect::<Result<Vec<_>>>()?;

    let text: String = functions.iter().map(ToString::to_string).collect();
    let semantic: Vec<_> = ["Binary", "FlagOp", "FloatOp", "Trap", "Unary"]
        .iter()
        .filter(|name| text.contains(&format!("{name} ::")))
        .map(|name| match *name {
            "FlagOp" => quote!(Flag as FlagOp),
            other => {
                let other = format_ident!("{other}");
                quote!(#other)
            }
        })
        .collect();
    let semantic =
        (!semantic.is_empty()).then(|| quote!(use binbun_semantics::ir::{#(#semantic),*};));
    let named = text.contains("registers ::").then(|| {
        quote!(
            use crate::registers;
        )
    });
    let tokens = quote! {
        use binbun_aarch64::Encoding;
        #semantic

        use crate::lifter::Lifter;
        #named

        /// The encodings with semantics.
        pub const ENCODINGS: [Encoding; #supported_count] = [#(Encoding::#supported),*];

        /// Lifts an instruction of `encoding`; false if no semantics cover it.
        #[expect(clippy::wildcard_enum_match_arm, reason = "most encodings have no semantics yet")]
        #[expect(clippy::too_many_lines, reason = "one arm per entry")]
        pub fn lift(l: &mut Lifter<'_>, encoding: Encoding) -> bool {
            match encoding {
                #(#arms)*
                _ => return false,
            }
            true
        }

        #(#functions)*
    };
    Ok(GeneratedFile {
        path: PathBuf::from("crates/binbun-aarch64-lift/src/generated.rs"),
        notice: NOTICE,
        docs: vec!["Semantics of each covered encoding, from `semantics/*.rs`.".to_owned()],
        tokens,
    })
}
