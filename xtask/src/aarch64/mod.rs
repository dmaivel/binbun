//! Generation of `binbun-aarch64` from Arm's AARCHMRS package
//! (`third_party/aarchmrs`) and the hand-written tables here.
//!
//! - `model.rs`: each A64 encoding's fixed bits (should-be bits excluded),
//!   field-condition exclusions, features, FAT tag.
//! - `tree.rs`: the overlap check and the decode tree.
//! - `undefined.rs` (hand-written) and `reserved.rs` (from the syntax): the
//!   decode-time checks, compiled by `checks.rs`.
//! - `symbols/` (hand-written, one file per slice of the instruction set):
//!   what each assembly symbol means as operands; `aliases.rs`: alias
//!   selection; both compiled into the decoder's `syntax.rs` by `syntax.rs`.
//! - `sysreg.rs`: system register and system operation names from
//!   `Registers.json` and LLVM 22's differences, into the decoder's
//!   `sysreg.rs`.
//! - `flow.rs` (hand-written): how each encoding transfers control and the
//!   condition it tests, into the decoder's `flow.rs`.
//! - `access/`: operand access, memory accesses, implicit registers and
//!   condition flags of each form, from the syntax and the hand-written
//!   rules in `access/rules.rs`, into the decoder's `access.rs`.
//! - `emit.rs`: the other generated modules.
//! - `lift.rs`: `binbun-aarch64-lift`'s semantics, checked against the
//!   decoder's operand access and flags.

