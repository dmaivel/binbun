/// The vendored package, relative to the workspace root.
const PACKAGE: &str = "third_party/aarchmrs/AARCHMRS_OPENSOURCE_A_profile_FAT-2026-09.tar.gz";

/// Directory of the generated modules, relative to the workspace root.
const OUTPUT: &str = "crates/binbun-aarch64/src/generated";

/// Provenance notice for files derived from AARCHMRS.
pub const AARCHMRS_NOTICE: &[&str] = &[
    "@generated by `cargo xtask codegen` from Arm's AARCHMRS package in",
    "third_party/aarchmrs and the tables in xtask/src/aarch64. Do not edit;",
    "edit the generator instead.",
    "",
    "Derived from the Arm A-profile Machine Readable Specification, Copyright",
    "2010-2026 Arm Limited or its affiliates, licensed under the BSD 3-Clause",
    "license (third_party/aarchmrs/notice.html).",
];

/// Path of the generated module `name`.
fn output(name: &str) -> PathBuf {
    Path::new(OUTPUT).join(format!("{name}.rs"))
}

/// Reads the vendored package and generates every AArch64 module.
pub fn generate(root: &Path) -> Result<Vec<GeneratedFile>> {
    let started = Instant::now();
    let package = Package::read(root.join(PACKAGE))?;
    let parsed = started.elapsed();
    let analysing = Instant::now();
    let mut encodings = model::collect(&package)?;
    encodings.sort_by(|a, b| a.name().cmp(b.name()));
    let overlaps = tree::overlaps(&encodings)?;
    let tree = tree::Tree::build(&encodings);
    let rejected = checks::rejected(&encodings, &package)?;
    let (syntax, forms) = syntax::generate(&encodings, &package)?;
    let access = access::generate(&encodings, &package)?;
    let analysed = analysing.elapsed();

    let stats = tree.stats();
    let (undefined_encodings, undefined_tests) = Rejected::count(&rejected.undefined);
    let (unpredictable_encodings, unpredictable_tests) = Rejected::count(&rejected.unpredictable);
    eprintln!(
        "aarch64: AARCHMRS read in {:.2?}, analysed in {:.2?}; {} encodings ({} FAT-only), {} \
         overlaps resolved by specificity; decode tree: {} switches, {} bit tests, {} leaves \
         (by candidates: {:?}), depth {}; UNDEFINED: {} encodings, {} tests; UNPREDICTABLE: {} \
         encodings, {} tests; {} bit tables; syntax of {} forms",
        parsed,
        analysed,
        encodings.len(),
        encodings.iter().filter(|e| e.fat).count(),
        overlaps.len(),
        stats.switches,
        stats.bits,
        stats.leaves,
        stats.candidates.get(1..).unwrap_or_default(),
        stats.depth,
        undefined_encodings,
        undefined_tests,
        unpredictable_encodings,
        unpredictable_tests,
        rejected.tables.len(),
        forms,
    );

    let fat = model::fat_features(&package.features);
    let features: BTreeSet<&str> = encodings
        .iter()
        .flat_map(|e| e.features.iter().copied())
        .collect();
    let features: Vec<&str> = features.into_iter().collect();
    let fat_flags: Vec<bool> = features.iter().map(|f| fat.contains(f)).collect();

    Ok(vec![
        emit::features(&features, &fat_flags)?,
        emit::encodings(&encodings)?,
        emit::decode(&encodings, &tree, &rejected)?,
        syntax,
        access,
        sysreg::generate(&package)?,
        flow::generate(&encodings)?,
        lift::generate(root, &encodings)?,
    ])
}
