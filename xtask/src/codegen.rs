//! Rendering, formatting and writing generated source files.

use std::fmt::Write as _;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use proc_macro2::{Literal, TokenStream};

use crate::Result;

/// An integer literal without a type suffix (`8`, not `8u8`).
pub fn lit(value: impl Into<u64>) -> Literal {
    Literal::u64_unsuffixed(value.into())
}

/// A length or count literal without a type suffix.
pub fn count(value: usize) -> Literal {
    Literal::usize_unsuffixed(value)
}

/// A byte as a hexadecimal literal (`0x0f`).
pub fn hex(value: u8) -> Literal {
    format!("{value:#04x}")
        .parse()
        .unwrap_or_else(|_| Literal::u8_unsuffixed(value))
}

/// What to do with the generated files.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Action {
    /// Overwrite files that changed.
    Write,
    /// Report files that would change, without writing.
    Check,
}

/// One generated Rust source file.
#[derive(Debug)]
pub struct GeneratedFile {
    /// Path relative to the workspace root.
    pub path: PathBuf,
    /// Licence and provenance lines placed at the top, without `//`.
    pub notice: &'static [&'static str],
    /// Module documentation, one line per entry, without `//!`.
    pub docs: Vec<String>,
    /// The code.
    pub tokens: TokenStream,
}

/// Provenance notice for files derived from XED's datafiles.
pub const XED_NOTICE: &[&str] = &[
    "@generated by `cargo xtask codegen` from Intel XED's datafiles in",
    "third_party/xed. Do not edit; edit the generator in xtask/ instead.",
    "",
    "Derived from Intel XED, Copyright (c) 2026 Intel Corporation, licensed",
    "under the Apache License, Version 2.0 (third_party/xed/LICENSE).",
];

/// Renders `files` and writes or checks them. Returns whether every file was
/// already up to date or has been written.
pub fn emit(root: &Path, files: &[GeneratedFile], action: Action) -> Result<bool> {
    let mut up_to_date = true;
    for file in files {
        let path = root.join(&file.path);
        let source = render(file)?;
        let current = std::fs::read_to_string(&path).ok();
        if current.as_deref() == Some(source.as_str()) {
            continue;
        }
        match action {
            Action::Write => {
                if let Some(parent) = path.parent() {
                    std::fs::create_dir_all(parent)?;
                }
                std::fs::write(&path, source)?;
                eprintln!("wrote {}", file.path.display());
            }
            Action::Check => {
                eprintln!("out of date: {}", file.path.display());
                up_to_date = false;
            }
        }
    }
    Ok(up_to_date)
}

/// The file's final text: notice, docs, then the code. prettyplease turns doc
/// attributes back into `///` comments; rustfmt then makes the result match
/// `cargo fmt` exactly.
fn render(file: &GeneratedFile) -> Result<String> {
    let mut text = String::new();
    for line in file.notice {
        writeln!(text, "//{}{line}", if line.is_empty() { "" } else { " " })?;
    }
    text.push('\n');
    for line in &file.docs {
        writeln!(text, "//!{}{line}", if line.is_empty() { "" } else { " " })?;
    }
    text.push('\n');
    text.push_str(&prettyplease::unparse(&syn::parse2(file.tokens.clone())?));
    rustfmt(&text)
}

fn rustfmt(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::inherit())
        .spawn()?;
    child
        .stdin
        .take()
        .ok_or("rustfmt has no stdin")?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        return Err(format!("rustfmt failed on generated code ({})", output.status).into());
    }
    Ok(String::from_utf8(output.stdout)?)
}
