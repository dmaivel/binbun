//! `cargo xtask header`: the large enumerations of the C API's header,
//! `crates/binbun-capi/include/binbun/disasm_generated.h`, from the
//! decoders' own tables (x86 mnemonics, registers, categories, extensions,
//! ISA sets; AArch64 encodings).
//!
//! The ids are the library's: 1-based, 0 for none (the C API adds one to the
//! decoders' 0-based enumerations; x86 registers are 1-based already). The
//! rest of the header is written by hand (`disasm.h`).

use std::fmt::Write as _;
use std::path::Path;

use binbun_aarch64::Encoding;
use binbun_x86::{Category, Extension, Form, IsaSet, Mnemonic, Register};

use crate::Result;
use crate::codegen::Action;

/// Where the generated header goes, from the workspace root.
const PATH: &str = "crates/binbun-capi/include/binbun/disasm_generated.h";

/// Writes or checks the header; returns whether it was up to date or has
/// been written.
pub fn run(root: &Path, action: Action) -> Result<bool> {
    let text = generate()?;
    let path = root.join(PATH);
    if std::fs::read_to_string(&path).ok().as_deref() == Some(text.as_str()) {
        return Ok(true);
    }
    match action {
        Action::Write => {
            std::fs::write(&path, text)?;
            eprintln!("wrote {PATH}");
            Ok(true)
        }
        Action::Check => {
            eprintln!("out of date: {PATH} (run `cargo xtask header`)");
            Ok(false)
        }
    }
}

/// The header's text.
fn generate() -> Result<String> {
    let mut out = String::new();
    out.push_str(
        "/* @generated by `cargo xtask header` from binbun's decoder tables. Do not\n \
         * edit; see xtask/src/header.rs.\n \
         *\n \
         * The ids of binbun/disasm.h: 1-based, 0 for none, stable within one\n \
         * version of the library. Included by binbun/disasm.h. */\n\
         #ifndef BINBUN_DISASM_GENERATED_H\n\
         #define BINBUN_DISASM_GENERATED_H\n\n\
         #include <stdint.h>\n\n",
    );
    enumeration(
        &mut out,
        "An x86 mnemonic: XED's iclass.",
        "binbun_x86_mnemonic",
        "BINBUN_X86_MNEMONIC_",
        Mnemonic::ALL.iter().map(|m| m.as_str().to_owned()),
    )?;
    writeln!(
        out,
        "/* An x86 form: XED's iform, named by binbun_x86_form_name. */\n\
         typedef uint16_t binbun_x86_form;\n\
         #define BINBUN_X86_FORM_COUNT {}\n",
        Form::COUNT
    )?;
    enumeration(
        &mut out,
        "An x86 register.",
        "binbun_x86_register",
        "BINBUN_X86_REG_",
        Register::ALL.iter().map(|r| format!("{r:?}")),
    )?;
    enumeration(
        &mut out,
        "An x86 instruction category.",
        "binbun_x86_category",
        "BINBUN_X86_CATEGORY_",
        Category::ALL.iter().map(|c| c.as_str().to_owned()),
    )?;
    enumeration(
        &mut out,
        "An x86 ISA extension.",
        "binbun_x86_extension",
        "BINBUN_X86_EXTENSION_",
        Extension::ALL.iter().map(|e| e.as_str().to_owned()),
    )?;
    enumeration(
        &mut out,
        "An x86 feature set (what CPUID must report).",
        "binbun_x86_isa_set",
        "BINBUN_X86_ISA_SET_",
        IsaSet::ALL.iter().map(|s| s.as_str().to_owned()),
    )?;
    enumeration(
        &mut out,
        "An A64 encoding, as Arm's specification names it.",
        "binbun_aarch64_encoding",
        "BINBUN_AARCH64_ENC_",
        Encoding::ALL.iter().map(|e| e.name().to_owned()),
    )?;
    out.push_str("#endif\n");
    Ok(out)
}

/// Appends a `typedef uint16_t` and its constants, numbered from 1 in the
/// order of `names`, with `_COUNT` the number of them.
fn enumeration(
    out: &mut String,
    doc: &str,
    type_name: &str,
    prefix: &str,
    names: impl Iterator<Item = String>,
) -> Result<()> {
    writeln!(out, "/* {doc} */\ntypedef uint16_t {type_name};\nenum {{")?;
    writeln!(out, "    {prefix}NONE = 0,")?;
    let mut count = 0;
    for (index, name) in names.enumerate() {
        let identifier = name.replace(['-', '.'], "_");
        if identifier.is_empty()
            || !identifier
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '_')
        {
            return Err(format!("{type_name}: `{name}` is no C identifier").into());
        }
        writeln!(out, "    {prefix}{identifier} = {},", index + 1)?;
        count = index + 1;
    }
    writeln!(out, "}};\n#define {prefix}COUNT {count}\n")?;
    Ok(())
}
