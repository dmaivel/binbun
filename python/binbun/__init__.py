"""binbun as a Python library: open a binary, read its functions, listing,
cross-references and C (with each line's machine instructions), verify
what the C says; name, comment, type and correct it in transactions
(each one undo step).

>>> import binbun
>>> with binbun.open("/usr/bin/true", project=False) as db:   # doctest: +SKIP
...     f = db.functions.get_by_name("main")
...     print(db.decompile(f).text)
...     with db.transaction("Name the entry"):
...         db.functions.set_name(f, "entry_point")

``import binbun`` loads the extension only: no thread starts, no plugin
loads, until a database is opened.

``binbun.connect()`` talks to a running binbun GUI instead (or to a
script's ``db.serve()``) over the user's own socket: its writes land in
the GUI's history, one undo step per run.

The decoders need no database: ``binbun.x86`` and ``binbun.aarch64``, with
the vocabulary they share here (``Status``, ``Branch``, ``Token``...), and
one decoder for both, ``binbun.disassemble(data, arch=binbun.Arch.X86)``
(``Decoder``, ``Instruction``), whose instructions give the native ones
as ``.x86`` and ``.aarch64``.
"""

