def without_header(path: Path) -> str:
    text = path.read_text(encoding="utf-8")
    if path.suffix == ".py":
        tree = ast.parse(text)
        if not (
            tree.body
            and isinstance(tree.body[0], ast.Expr)
            and isinstance(tree.body[0].value, ast.Constant)
        ):
            raise Failure(f"{path}: no docstring at the top")
        body = text.split("\n")[tree.body[0].end_lineno :]
    elif path.suffix == ".c":
        lines = text.split("\n")
        if not lines[0].startswith("/*"):
            raise Failure(f"{path}: no comment at the top")
        end = next(i for i, line in enumerate(lines) if line.rstrip().endswith("*/"))
        body = lines[end + 1 :]
    else:
        prefix = "//!" if path.suffix == ".rs" else "//"
        lines = text.split("\n")
        if not lines[0].startswith(prefix):
            raise Failure(f"{path}: no {prefix} comment at the top")
        body = lines[
            next(i for i, line in enumerate(lines) if not line.startswith(prefix)) :
        ]
    return "\n".join(body).strip("\n") + "\n"


def landing() -> dict[Path, str]:
    """The decoders' panel, in each language, and the decompiler's, in the
    languages that have it (the C API has the decoders only)."""
    panels = {
        "quick_start": (("python", "py"), ("rust", "rs"), ("c", "c"), ("cpp", "cpp")),
        "decompiler_quick_start": (("python", "py"), ("rust", "rs")),
    }
    return {
        SNIPPETS / f"{name}.{suffix}": without_header(
            ROOT / "examples" / folder / f"{name}.{suffix}"
        )
        for name, languages in panels.items()
        for folder, suffix in languages
    }


