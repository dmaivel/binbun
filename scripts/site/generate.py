# The C API, from its headers


def comment_text(lines: list[str]) -> str:
    text = []
    for line in lines:
        line = line.strip()
        line = re.sub(r"^/\*\s?", "", line)
        line = re.sub(r"\s*\*/$", "", line)
        line = re.sub(r"^\*(?:\s|$)", "", line)
        text.append(line)
    return "\n".join(text).strip("\n")


def declared_names(code: list[str]) -> list[str]:
    names: list[str] = []
    joined = "\n".join(code)
    for line in code:
        found = re.match(r"#define\s+(\w+)", line)
        if found:
            names.append(found.group(1))
    names += re.findall(r"^\}\s*(\w+)\s*;", joined, re.MULTILINE)
    names += re.findall(r"^typedef\s+[\w\s\*]+?\b(\w+)\s*;", joined, re.MULTILINE)
    if not names:
        # A prototype: the first name before a parenthesis that is no
        # macro (BINBUN_DEPRECATED(...)).
        for function in re.finditer(r"\b(\w+)\s*\(", joined):
            if not re.fullmatch(r"[A-Z0-9_]+", function.group(1)):
                names.append(function.group(1))
                break
    seen: list[str] = []
    for name in names:
        if name not in seen:
            seen.append(name)
    return seen


def c_reference() -> str:
    out = [front_matter("C API", 20)]
    out.append(
        "`#include <binbun/binbun.h>` (or one part's header) and link `libbinbun`, from a release's `libbinbun-*` archive. "
        "Generated from the comments of the headers; the ids `binbun/disasm.h` names (mnemonics, registers, forms, encodings) "
        "are constants in `binbun/disasm_generated.h`, which it includes, and `binbun/core.hpp` and `binbun/disasm.hpp` wrap them for C++. "
        "The guide is [C and C++](@/docs/c-api.md)."
    )
    out.append("")
    for header in HEADERS:
        out += header_reference(header)
    return "\n".join(out).rstrip("\n") + "\n"


def header_reference(header: Path) -> list[str]:
    """The reference's section for one header: its name, its top comment,
    then each banner's part and each declaration with its comment."""
    name = header.name
    lines = header.read_text(encoding="utf-8").split("\n")
    if not lines[0].startswith("/*"):
        raise Failure(f"{header}: no comment at the top")
    end = next(i for i, line in enumerate(lines) if line.rstrip().endswith("*/"))
    intro = comment_text(lines[: end + 1])
    intro = re.sub(rf"^binbun/{re.escape(name)}:\s*", "", intro)
    guard = "BINBUN_" + re.sub(r"\W", "_", name).upper()
    out = [f"## `binbun/{name}`", ""]
    out.append(markdown(intro[:1].upper() + intro[1:], name, c_comment=True))
    out.append("")
    i = end + 1
    depth_if = 0
    items: list[tuple[list[str], list[str]]] = []
    chunk: list[str] = []

    def take_chunk() -> None:
        current: tuple[list[str], list[str]] | None = None
        j = 0
        while j < len(chunk):
            line = chunk[j]
            if line.startswith("/*"):
                comment = [line]
                while not comment[-1].rstrip().endswith("*/"):
                    j += 1
                    comment.append(chunk[j])
                current = (comment, [])
                items.append(current)
            else:
                if current is None:
                    current = ([], [])
                    items.append(current)
                current[1].append(line)
            j += 1
        chunk.clear()

    while i < len(lines):
        line = lines[i]
        banner = re.match(r"^/\* -{8,}$", line)
        if banner:
            take_chunk()
            title = lines[i + 1].strip().lstrip("* ").strip()
            items.append((["### " + title], []))
            i += 3
            continue
        if re.match(
            rf"#(ifndef {guard}|define {guard}|include|ifdef __cplusplus)",
            line,
        ) or line.startswith('extern "C"'):
            if line.startswith("#ifdef __cplusplus"):
                depth_if += 1
            i += 1
            continue
        if line.startswith("#endif") and (depth_if or i >= len(lines) - 3):
            depth_if = max(depth_if - 1, 0)
            i += 1
            continue
        if line == "}" and depth_if:
            i += 1
            continue
        if not line.strip():
            take_chunk()
        else:
            chunk.append(line)
        i += 1
    take_chunk()

    for comment, code in items:
        if comment and comment[0].startswith("### "):
            out.append(comment[0])
            out.append("")
            continue
        if not code:
            raise Failure(f"{header}: a comment documents nothing: {comment[0]!r}")
        names = declared_names(code)
        if not names:
            raise Failure(f"{header}: no name declared in {code[0]!r}")
        out.append("#### " + ", ".join(names))
        out.append("")
        out.append("```c\n" + "\n".join(code) + "\n```")
        out.append("")
        if comment:
            out.append(
                markdown(comment_text(comment), f"{name} {names[0]}", c_comment=True)
            )
            out.append("")
    return out


