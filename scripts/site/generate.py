# The extension's docstrings, from crates/binbun-py/src


@dataclass
class RustDocs:
    classes: dict[tuple[str, str], str] = field(default_factory=dict)
    members: dict[tuple[str, str, str], str] = field(default_factory=dict)
    functions: dict[tuple[str, str], str] = field(default_factory=dict)

    def class_doc(self, module: str, name: str) -> str | None:
        return self.classes.get((module, name)) or unique(
            self.classes, name, lambda key: key[1]
        )

    def member_doc(self, module: str, cls: str, name: str) -> str | None:
        found = self.members.get((module, cls, name))
        if found is None:
            matches = {
                doc for (_, c, n), doc in self.members.items() if c == cls and n == name
            }
            found = matches.pop() if len(matches) == 1 else None
        return found

    def function_doc(self, module: str, name: str) -> str | None:
        return self.functions.get((module, name)) or unique(
            self.functions, name, lambda key: key[1]
        )


def unique(table: dict, name: str, key_name) -> str | None:
    matches = [doc for key, doc in table.items() if key_name(key) == name]
    return matches[0] if len(matches) == 1 else None


def balanced(text: str) -> bool:
    text = re.sub(r'"(?:\\.|[^"\\])*"', "", text)
    return text.count("[") == text.count("]") and text.count("(") == text.count(")")


def attribute_name(attributes: list[str], key: str) -> str | None:
    for attribute in attributes:
        found = re.search(key + r'\s*=\s*"([^"]+)"', attribute)
        if found:
            return found.group(1)
    return None


def rust_docs() -> RustDocs:
    """The `///` comments pyo3 makes into docstrings: of each #[pyclass]
    struct and its fields, each method of its #[pymethods] impl and each
    #[pyfunction]. A class is named as its `#[pyclass(name = ...)]` says,
    else as its struct; methods belong to the struct of their own file
    (x86's and AArch64's `Instruction` are two classes). Relies on
    rustfmt's layout: items at column 0, their members at column 4."""
    docs = RustDocs()
    pending: dict[tuple[str, str], list[tuple[str, str, str]]] = {}
    # (file, struct) -> (module, Python class name)
    struct_class: dict[tuple[str, str], tuple[str, str]] = {}
    for path in sorted(EXTENSION.glob("*.rs")):
        file_module = {"x86.rs": "binbun.x86", "aarch64.rs": "binbun.aarch64"}.get(
            path.name, "binbun._native"
        )
        comment: list[str] = []
        attributes: list[str] = []
        attribute: str | None = None
        context: tuple | None = None
        for line in path.read_text(encoding="utf-8").split("\n"):
            stripped = line.strip()
            indent = len(line) - len(line.lstrip())
            if attribute is not None:
                attribute += " " + stripped
                if balanced(attribute):
                    attributes.append(attribute)
                    attribute = None
                continue
            if stripped.startswith("///"):
                comment.append(
                    stripped[4:] if stripped.startswith("/// ") else stripped[3:]
                )
                continue
            if stripped.startswith("#["):
                if balanced(stripped):
                    attributes.append(stripped)
                else:
                    attribute = stripped
                continue
            if stripped.startswith("//"):
                continue
            text = "\n".join(comment)
            if indent == 0 and stripped:
                if stripped.startswith("}"):
                    context = None
                pyclass = next(
                    (a for a in attributes if a.startswith("#[pyclass")), None
                )
                struct = re.match(r"(?:pub(?:\([^)]*\))?\s+)?struct\s+(\w+)", stripped)
                function = re.match(r"(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?fn\s+(\w+)", stripped)
                implementation = re.match(r"impl(?:<[^>]*>)?\s+(\w+)\s*\{", stripped)
                if struct and pyclass:
                    module = attribute_name([pyclass], "module") or file_module
                    name = attribute_name([pyclass], "name") or struct.group(1)
                    struct_class[(path.name, struct.group(1))] = (module, name)
                    if text:
                        docs.classes[(module, name)] = text
                    get_all = "get_all" in pyclass
                    context = (
                        None
                        if stripped.endswith(";")
                        else ("struct", module, name, get_all)
                    )
                elif implementation and "#[pymethods]" in attributes:
                    context = ("impl", file_module, (path.name, implementation.group(1)))
                elif function and any(a.startswith("#[pyfunction") for a in attributes):
                    name = attribute_name(attributes, "name") or function.group(1)
                    if text:
                        docs.functions[(file_module, name)] = text
                elif not stripped.startswith("}"):
                    context = None
            elif indent == 4 and context and stripped:
                if context[0] == "struct":
                    member = re.match(r"(?:pub(?:\([^)]*\))?\s+)?(\w+)\s*:", stripped)
                    gets = context[3] or any(
                        re.match(r"#\[pyo3\([^)]*\bget\b", a) for a in attributes
                    )
                    if member and gets and text:
                        name = attribute_name(attributes, "name") or member.group(1)
                        docs.members[(context[1], context[2], name)] = text
                else:
                    method = re.match(r"(?:pub(?:\([^)]*\))?\s+)?(?:const\s+)?fn\s+(\w+)", stripped)
                    if (
                        method
                        and text
                        and not any(a.startswith("#[setter") for a in attributes)
                    ):
                        name = method.group(1)
                        getter = next(
                            (a for a in attributes if a.startswith("#[getter")), None
                        )
                        if getter:
                            named = re.match(r"#\[getter\((\w+)\)\]", getter)
                            name = (
                                named.group(1) if named else name.removeprefix("get_")
                            )
                        if "#[new]" in attributes:
                            name = "__new__"
                        name = attribute_name(attributes, "name") or name
                        pending.setdefault(context[2], []).append(
                            (context[1], name, text)
                        )
            comment = []
            attributes = []
    for cls, methods in pending.items():
        for file_module, name, text in methods:
            module, python = struct_class.get(cls, (file_module, cls[1]))
            docs.members[(module, python, name)] = text
    return docs


