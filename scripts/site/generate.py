# The command line, from binbun --help

NO_GUI = re.compile(
    r"^this binbun was built without the GUI.*?\n\n", re.MULTILINE | re.DOTALL
)


def run_help(binbun: str, *arguments: str) -> str:
    environment = {
        "PATH": os.environ.get("PATH", ""),
        "HOME": os.environ.get("HOME", "/"),
        "LC_ALL": "C",
    }
    try:
        result = subprocess.run(
            [binbun, *arguments, "--help"],
            check=False,
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=30,
            env=environment,
            cwd=ROOT,
        )
    except FileNotFoundError:
        raise Failure(
            f"no binbun at {binbun!r}: give --binbun PATH or set BINBUN"
        ) from None
    return (result.stdout + result.stderr).rstrip("\n") + "\n"


def cli_reference(binbun: str) -> str:
    text = run_help(binbun)
    if not text.startswith("usage:"):
        raise Failure(f"{binbun} --help printed no usage: {text[:200]!r}")
    text = NO_GUI.sub("", text)
    usage = text.partition("\n\n")[0]
    commands: dict[str, list[str]] = {}
    current: list[str] | None = None
    for line in usage.split("\n")[1:]:
        found = re.match(r"^  binbun ([a-z][a-z-]*)\b", line)
        if found:
            current = commands.setdefault(found.group(1), [])
            current.append(line[2:])
        elif line.startswith("   ") and current is not None:
            current.append(line[2:])
        else:
            current = None
    out = [front_matter("Command line", 30)]
    out.append(
        "Generated from `binbun --help` and each command's own usage, as the Linux build prints them. "
        "The guide is [The command line](@/docs/command-line.md)."
    )
    out.append("")
    out.append("## Usage")
    out.append("")
    out.append("```text\n" + text.rstrip("\n") + "\n```")
    out.append("")
    out.append("## Commands")
    out.append("")
    for command, lines in commands.items():
        # A command with no usage of its own prints the whole usage (on
        # an error, without the folders).
        own = run_help(binbun, command)
        own_usage = NO_GUI.sub("", own).partition("\n\n")[0].rstrip("\n")
        if own.startswith("usage:") and own_usage != usage.rstrip("\n"):
            body = re.sub(r"^usage:", "      ", own.rstrip("\n"))
            body = "\n".join(dedent(body.split("\n"))).strip()
        else:
            body = "\n".join(dedent(lines))
        out.append(f"### binbun {command}")
        out.append("")
        out.append("```text\n" + body + "\n```")
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


