def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("parts", nargs="*", metavar="python|c|cli|landing")
    parser.add_argument(
        "--check",
        action="store_true",
        help="write nothing; fail if a file is not current",
    )
    parser.add_argument(
        "--binbun",
        default=os.environ.get("BINBUN", "binbun"),
        help="the binbun binary for the CLI page",
    )
    arguments = parser.parse_args()
    every = ["python", "c", "cli", "landing"]
    unknown = sorted(set(arguments.parts) - set(every))
    if unknown:
        parser.error(f"no part {', '.join(unknown)}: python, c, cli, landing")
    parts = arguments.parts or every
    files: dict[Path, str] = {}
    try:
        if "python" in parts:
            files[REFERENCE / "python.md"] = PythonReference().render()
        if "c" in parts:
            files[REFERENCE / "c.md"] = c_reference()
        if "cli" in parts:
            files[REFERENCE / "cli.md"] = cli_reference(arguments.binbun)
        if "landing" in parts:
            files.update(landing())
    except Failure as failure:
        print(f"generate.py: {failure}", file=sys.stderr)
        return 1
    stale = []
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        stale.append(path)
        if not arguments.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    if arguments.check and stale:
        for path in stale:
            print(
                f"generate.py: {path.relative_to(ROOT)} is not current: run scripts/site/generate.py",
                file=sys.stderr,
            )
        return 1
    for path in stale:
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
