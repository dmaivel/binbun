# Docstring text to Markdown


# Pointers into the private design notes, which the website never shows.
PRIVATE = [
    re.compile(r"\s*\(``?research/[^`]*``?(?:\s*§[\d.]+(?:,\s*§[\d.]+)*)?\)"),
    re.compile(r",\s*slice \d+(?=\))"),
    re.compile(r"\s*\(slice \d+\)"),
]
LEAK = re.compile(r"research/|§|\bslice \d")


def scrub(text: str, where: str) -> str:
    for pattern in PRIVATE:
        text = pattern.sub("", text)
    leak = LEAK.search(text)
    if leak:
        raise Failure(
            f"{where}: a reference to internal notes ({leak.group(0)!r}) the scrub does not remove"
        )
    return text


# binbun's C names (`binbun_x86_decode`, `BINBUN_<ARCH>_MAX_TEXT`), set
# as code in the header's comments.
C_NAME = re.compile(r"\b(?:BINBUN|binbun)_(?:[\w]|<\w+>)*(?:\(\))?")


def inline(text: str, *, c_comment: bool = False) -> str:
    """reST and rustdoc inline markup as Markdown; `<` and `>` outside
    code spans escaped. In a C comment, binbun's names set as code and
    `*` and `_` escaped."""
    text = re.sub(
        r":(?:class|func|meth|attr|mod|data|exc|obj):`~?([^`]+)`", r"``\1``", text
    )
    text = re.sub(r"``(.+?)``", lambda m: "`" + m.group(1) + "`", text)
    text = re.sub(r"\[([^\]]+)\]\[`?[^\]]*`?\]", r"\1", text)
    text = re.sub(r"\[(`[^`\]]+`)\](?![(\[])", r"\1", text)
    text = re.sub(r"(\w)::$", r"\1:", text)
    parts = re.split(r"(`[^`]*`)", text)
    for i in range(0, len(parts), 2):
        if c_comment:
            pieces = C_NAME.split(parts[i])
            names = [f"`{name}`" for name in C_NAME.findall(parts[i])]
            plain = [
                escape(piece).replace("*", r"\*").replace("_", r"\_")
                for piece in pieces
            ]
            parts[i] = "".join(
                itertools.chain.from_iterable(
                    itertools.zip_longest(plain, names, fillvalue="")
                )
            )
        else:
            parts[i] = escape(parts[i])
    return "".join(parts)


def escape(text: str) -> str:
    return text.replace("<", "&lt;").replace(">", "&gt;")


LIST_ITEM = re.compile(r"^(?:[-*+]|\d+[.)])\s+")


def markdown(text: str, where: str, *, c_comment: bool = False) -> str:
    """A docstring or comment as Markdown blocks: one line per paragraph
    and per list item, doctests and literal blocks fenced."""
    text = scrub(text, where)
    lines = text.split("\n")
    blocks: list[tuple[str, str]] = []
    paragraph: list[str] = []
    kind = "p"

    def flush() -> None:
        nonlocal kind
        if paragraph:
            blocks.append((kind, inline(" ".join(paragraph), c_comment=c_comment)))
            paragraph.clear()
        kind = "p"

    i = 0
    while i < len(lines):
        line = lines[i].rstrip()
        stripped = line.strip()
        if stripped.startswith("```"):
            flush()
            language = stripped[3:].strip() or "text"
            body = []
            i += 1
            while i < len(lines) and not lines[i].strip().startswith("```"):
                body.append(lines[i].rstrip())
                i += 1
            blocks.append(
                ("code", f"```{language}\n" + "\n".join(dedent(body)) + "\n```")
            )
        elif stripped.startswith(">>>"):
            flush()
            body = []
            while i < len(lines) and lines[i].strip():
                body.append(re.sub(r"\s*# doctest:.*$", "", lines[i].rstrip()))
                i += 1
            blocks.append(("code", "```python\n" + "\n".join(dedent(body)) + "\n```"))
            continue
        elif not stripped:
            flush()
        elif line.startswith("    ") and not paragraph:
            body = []
            while i < len(lines) and (
                lines[i].startswith("    ") or not lines[i].strip()
            ):
                body.append(lines[i].rstrip())
                i += 1
            while body and not body[-1]:
                body.pop()
            blocks.append(("code", "```text\n" + "\n".join(dedent(body)) + "\n```"))
            continue
        elif LIST_ITEM.match(stripped):
            flush()
            kind = "li"
            paragraph.append(stripped)
        else:
            paragraph.append(stripped)
        i += 1
    flush()
    out = ""
    for index, (kind, block) in enumerate(blocks):
        if index:
            out += "\n" if kind == "li" and blocks[index - 1][0] == "li" else "\n\n"
        out += block
    return out


def dedent(lines: list[str]) -> list[str]:
    indents = [len(line) - len(line.lstrip()) for line in lines if line.strip()]
    cut = min(indents, default=0)
    return [line[cut:] for line in lines]


def indent_definition(text: str) -> str:
    """Markdown blocks as a definition: `: ` before the first, the rest
    indented under it."""
    first, *rest = text.split("\n")
    return "\n".join(
        [": " + first] + [("    " + line) if line else "" for line in rest]
    )


