# The Python modules: stubs for the surface, sources for the docstrings


@dataclass
class PyDocs:
    """The docstrings of one module's source (`.py`)."""

    module: str | None = None
    objects: dict[str, str] = field(
        default_factory=dict
    )  # "Class", "Class.member", "function", "CONSTANT"


def docstring_of(node: ast.AST) -> str | None:
    doc = ast.get_docstring(node, clean=True)  # type: ignore[arg-type]
    return doc or None


def attribute_docs(body: list[ast.stmt], prefix: str, into: dict[str, str]) -> None:
    for before, after in itertools.pairwise(body):
        if (
            isinstance(after, ast.Expr)
            and isinstance(after.value, ast.Constant)
            and isinstance(after.value.value, str)
        ):
            target = None
            if isinstance(before, ast.AnnAssign) and isinstance(
                before.target, ast.Name
            ):
                target = before.target.id
            elif (
                isinstance(before, ast.Assign)
                and len(before.targets) == 1
                and isinstance(before.targets[0], ast.Name)
            ):
                target = before.targets[0].id
            if target:
                into[prefix + target] = inspect.cleandoc(after.value.value)


def py_docs(path: Path) -> PyDocs:
    docs = PyDocs()
    if not path.exists():
        return docs
    tree = ast.parse(path.read_text(encoding="utf-8"))
    docs.module = docstring_of(tree)
    attribute_docs(tree.body, "", docs.objects)
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            if doc := docstring_of(node):
                docs.objects[node.name] = doc
        elif isinstance(node, ast.ClassDef):
            if doc := docstring_of(node):
                docs.objects[node.name] = doc
            attribute_docs(node.body, node.name + ".", docs.objects)
            for member in node.body:
                if isinstance(member, (ast.FunctionDef, ast.AsyncFunctionDef)) and (
                    doc := docstring_of(member)
                ):
                    docs.objects.setdefault(f"{node.name}.{member.name}", doc)
    return docs


@dataclass
class Module:
    """A module's surface: its stub (or, without one, its source)."""

    name: str  # binbun._native
    tree: ast.Module
    docs: PyDocs
    stub: bool

    def defined(self) -> dict[str, ast.stmt]:
        found: dict[str, ast.stmt] = {}
        for node in self.tree.body:
            if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                found.setdefault(node.name, node)
            elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                found.setdefault(node.target.id, node)
        return found

    def exported(self) -> list[str] | None:
        for node in self.tree.body:
            if isinstance(node, (ast.Assign, ast.AnnAssign)):
                targets = (
                    node.targets if isinstance(node, ast.Assign) else [node.target]
                )
                if (
                    any(isinstance(t, ast.Name) and t.id == "__all__" for t in targets)
                    and node.value is not None
                ):
                    return [ast.literal_eval(element) for element in node.value.elts]  # type: ignore[attr-defined]
        return None

    def imports(self) -> dict[str, tuple[str, str]]:
        found = {}
        for node in self.tree.body:
            if isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
                for alias in node.names:
                    found[alias.asname or alias.name] = (node.module, alias.name)
        return found

    def aliases(self) -> dict[str, str]:
        """The private type aliases (`_Path = str | PathLike[str]`)."""
        found = {}
        for node in self.tree.body:
            if (
                isinstance(node, ast.Assign)
                and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
                and re.fullmatch(r"_[A-Z]\w*", node.targets[0].id)
            ):
                found[node.targets[0].id] = unparse(node.value)
        return found


# A private alias up to this long is written out where it is used; a
# longer one is listed with the module's types.
ALIAS_INLINE = 60


def load_module(name: str) -> Module:
    short = name.split(".", 1)[1] if "." in name else "__init__"
    stub = STUBS / f"{short}.pyi"
    source = STUBS / f"{short}.py"
    path = stub if stub.exists() else source
    return Module(
        name,
        ast.parse(path.read_text(encoding="utf-8")),
        py_docs(source),
        stub.exists(),
    )


SKIPPED_DUNDERS = {
    "__repr__",
    "__eq__",
    "__ne__",
    "__hash__",
    "__lt__",
    "__le__",
    "__gt__",
    "__ge__",
    "__init_subclass__",
    "__class_getitem__",
    "__post_init__",
    "__del__",
    "__reduce__",
    "__getstate__",
    "__setstate__",
    "__new__",
    "__init__",
}


def unparse(node: ast.AST | None) -> str:
    return ast.unparse(node) if node is not None else ""


def parameters(arguments: ast.arguments, drop_first: bool) -> str:
    positional = [(a, "posonly") for a in arguments.posonlyargs] + [
        (a, "pos") for a in arguments.args
    ]
    defaults: list[ast.expr | None] = [None] * (
        len(positional) - len(arguments.defaults)
    ) + list(arguments.defaults)
    entries = list(zip(positional, defaults))
    if drop_first and entries:
        entries = entries[1:]
    out: list[str] = []

    def one(arg: ast.arg, default: ast.expr | None) -> str:
        text = arg.arg
        if arg.annotation is not None:
            text += ": " + unparse(arg.annotation)
        if default is not None:
            text += (" = " if arg.annotation is not None else "=") + unparse(default)
        return text

    posonly = [e for e in entries if e[0][1] == "posonly"]
    for (arg, _), default in entries:
        out.append(one(arg, default))
        if posonly and (arg, "posonly") == posonly[-1][0]:
            out.append("/")
    if arguments.vararg:
        out.append("*" + one(arguments.vararg, None))
    elif arguments.kwonlyargs:
        out.append("*")
    for arg, default in zip(arguments.kwonlyargs, arguments.kw_defaults):
        out.append(one(arg, default))
    if arguments.kwarg:
        out.append("**" + one(arguments.kwarg, None))
    return ", ".join(out)


def decorator_names(node: ast.FunctionDef | ast.AsyncFunctionDef) -> list[str]:
    return [unparse(d) for d in node.decorator_list]


@dataclass
class Member:
    name: str
    terms: list[str]
    doc: str | None
    module: Module | None = None


def is_public(name: str) -> bool:
    return not name.startswith("_") or (
        name.startswith("__") and name.endswith("__") and name not in SKIPPED_DUNDERS
    )


ENUM_BASES = re.compile(r"^(?:enum\.)?(?:Int|Str)?(?:Enum|Flag|IntFlag)$")


class PythonReference:
    def __init__(self) -> None:
        self.rust = rust_docs()
        self.modules: dict[str, Module] = {}
        self.out: list[str] = []
        self.documented: set[str] = set()

    def module(self, name: str) -> Module:
        if name not in self.modules:
            self.modules[name] = load_module(name)
        return self.modules[name]

    def doc(
        self,
        module: Module,
        qualified: str,
        cls: str | None = None,
        member: str | None = None,
    ) -> str | None:
        """A docstring: the module source's, else the extension's."""
        found = module.docs.objects.get(qualified)
        if found:
            return found
        if cls and member:
            return self.rust.member_doc(module.name, cls, member)
        if cls:
            return self.rust.class_doc(module.name, cls)
        return self.rust.function_doc(module.name, qualified)

    def emit(self, text: str = "") -> None:
        self.out.append(text)

    def prose(self, text: str | None, where: str) -> None:
        if text:
            self.emit(markdown(text, where))
            self.emit()

    def function_term(
        self,
        node: ast.FunctionDef | ast.AsyncFunctionDef,
        prefix: str = "",
        drop_first: bool = False,
    ) -> str:
        returns = f" -> {unparse(node.returns)}" if node.returns is not None else ""
        return f"`{prefix}{node.name}({parameters(node.args, drop_first)}){returns}`"

    def expand(self, term: str, module: Module | None) -> str:
        if module is None:
            return term
        for name, value in module.aliases().items():
            if len(value) <= ALIAS_INLINE:
                term = re.sub(rf"\b{name}\b", value, term)
        return term

    def definitions(self, members: list[Member], where: str) -> None:
        for member in members:
            self.emit(
                " <br> ".join(self.expand(term, member.module) for term in member.terms)
            )
            body = markdown(member.doc, f"{where}.{member.name}") if member.doc else ""
            self.emit(indent_definition(body) if body else ":")
            self.emit()

    def class_members(
        self, module: Module, node: ast.ClassDef
    ) -> tuple[list[str], list[Member]]:
        enum_values: list[str] = []
        members: dict[str, Member] = {}
        writable: set[str] = set()
        for item in node.body:
            if isinstance(item, ast.Assign):
                for target in item.targets:
                    if isinstance(target, ast.Name) and not target.id.startswith("_"):
                        enum_values.append(f"{target.id} = {unparse(item.value)}")
            elif isinstance(item, ast.AnnAssign) and isinstance(item.target, ast.Name):
                name = item.target.id
                if name.startswith("_"):
                    continue
                term = f"`{name}: {unparse(item.annotation)}`"
                members.setdefault(name, Member(name, [term], None, module))
            elif isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                decorators = decorator_names(item)
                name = item.name
                if any(d.endswith(".setter") for d in decorators):
                    writable.add(name)
                    continue
                if name in ("__init__", "__new__"):
                    term = f"`{node.name}({parameters(item.args, True)})`"
                    key = "__init__"
                elif not is_public(name):
                    continue
                elif (
                    "property" in decorators
                    or "functools.cached_property" in decorators
                ):
                    annotation = (
                        unparse(item.returns) if item.returns is not None else "Any"
                    )
                    term = f"`{name}: {annotation}`"
                    key = name
                elif "staticmethod" in decorators:
                    term = self.function_term(item, f"{node.name}.")
                    key = name
                elif "classmethod" in decorators:
                    term = self.function_term(item, f"{node.name}.", drop_first=True)
                    key = name
                else:
                    term = self.function_term(item, drop_first=True)
                    key = name
                if key in members and "overload" in " ".join(decorators):
                    members[key].terms.append(term)
                    continue
                members.setdefault(key, Member(name, [term], None, module))
        for key, member in members.items():
            if key in writable:
                member.terms = [term + " (writable)" for term in member.terms]
            lookup = "__new__" if key == "__init__" else member.name
            member.doc = (
                module.docs.objects.get(f"{node.name}.{member.name}")
                or (
                    module.docs.objects.get(f"{node.name}.__init__")
                    if key == "__init__"
                    else None
                )
                or self.rust.member_doc(module.name, node.name, lookup)
            )
        ordered = ([members.pop("__init__")] if "__init__" in members else []) + list(
            members.values()
        )
        return enum_values, ordered

    def render_class(
        self, module: Module, node: ast.ClassDef, anchor: str, source: Module
    ) -> None:
        self.emit(f"### {node.name} {{#{anchor}}}")
        self.emit()
        bases = [unparse(base) for base in node.bases]
        if bases:
            self.emit(f"`class {node.name}({', '.join(bases)})`")
            self.emit()
        self.prose(
            source.docs.objects.get(node.name)
            or self.rust.class_doc(source.name, node.name),
            anchor,
        )
        enum_values, members = self.class_members(source, node)
        if enum_values and any(ENUM_BASES.match(base) for base in bases):
            self.emit("```python\n" + "\n".join(enum_values) + "\n```")
            self.emit()
        self.definitions(members, anchor)

    def render_items(
        self, entries: list[tuple[str, Module, ast.stmt]], public: str
    ) -> None:
        """Functions, then constants and types, then classes."""
        functions = [
            (n, m, s)
            for n, m, s in entries
            if isinstance(s, (ast.FunctionDef, ast.AsyncFunctionDef))
        ]
        values = [(n, m, s) for n, m, s in entries if isinstance(s, ast.AnnAssign)]
        classes = [(n, m, s) for n, m, s in entries if isinstance(s, ast.ClassDef)]
        if functions:
            self.emit(f"### Module functions {{#{public}-functions}}")
            self.emit()
            members = []
            for name, module, node in functions:
                members.append(
                    Member(
                        name, [self.function_term(node)], self.doc(module, name), module
                    )
                )  # type: ignore[arg-type]
            self.definitions(members, public)
        long_aliases = []
        for module in {m.name: m for _, m, _ in entries}.values():
            for name, value in module.aliases().items():
                if (
                    len(value) > ALIAS_INLINE
                    and f"{module.name}.{name}" not in self.documented
                ):
                    self.documented.add(f"{module.name}.{name}")
                    long_aliases.append(
                        Member(name, [f"`{name} = {value}`"], None, module)
                    )
        if values or long_aliases:
            self.emit(f"### Module constants and types {{#{public}-constants}}")
            self.emit()
            members = []
            for name, module, node in values:
                annotation = unparse(node.annotation)  # type: ignore[attr-defined]
                if annotation in ("TypeAlias", "typing.TypeAlias"):
                    term = f"`{name} = {unparse(node.value)}`"  # type: ignore[attr-defined]
                else:
                    term = f"`{name}: {annotation}`"
                members.append(Member(name, [term], self.doc(module, name), module))
            self.definitions(members + long_aliases, public)
        for name, module, node in classes:
            self.render_class(module, node, f"{public}.{name}", module)  # type: ignore[arg-type]
            self.documented.add(f"{module.name}.{name}")

    def resolve(self, module: Module, name: str) -> tuple[Module, ast.stmt] | None:
        defined = module.defined()
        if name in defined:
            return module, defined[name]
        imported = module.imports().get(name)
        if imported and imported[0].startswith("binbun"):
            return self.resolve(self.module(imported[0]), imported[1])
        return None

    def package(self) -> None:
        package = self.module("binbun")
        exported = package.exported() or []
        groups: dict[str, list[tuple[str, Module, ast.stmt]]] = {}
        for name in exported:
            found = self.resolve(package, name)
            if found is None:
                raise Failure(
                    f"binbun.{name}: in __all__ but defined in no stub or module"
                )
            module, node = found
            # Functions, constants and the extension's classes (with the
            # Python classes it returns) under binbun; the classes of the
            # other modules each under a heading of their own.
            group = (
                module.name
                if isinstance(node, ast.ClassDef)
                and module.name not in ("binbun._native", "binbun._results")
                else "binbun"
            )
            groups.setdefault(group, []).append((name, module, node))
        order = {
            "binbun": "binbun",
            "binbun._enums": "Enumerations",
            "binbun._errors": "Exceptions",
            "binbun._remote": "Connecting to the app",
            "binbun._talk": "Threads and suggestions",
        }
        unknown = set(groups) - set(order)
        if unknown:
            raise Failure(
                f"binbun exports from modules this generator does not place: {sorted(unknown)}"
            )
        for group, heading in order.items():
            entries = groups.get(group, [])
            if not entries:
                continue
            anchor = group.replace("binbun._", "binbun-")
            self.emit(f"## {heading} {{#{anchor}}}")
            self.emit()
            self.prose(
                package.docs.module
                if group == "binbun"
                else self.module(group).docs.module,
                group,
            )
            self.render_items(self.in_definition_order(entries), "binbun")

    def in_definition_order(
        self, entries: list[tuple[str, Module, ast.stmt]]
    ) -> list[tuple[str, Module, ast.stmt]]:
        def key(entry: tuple[str, Module, ast.stmt]) -> tuple[int, str, int]:
            _, module, node = entry
            kind = (
                0
                if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
                else 1
                if isinstance(node, ast.AnnAssign)
                else 2
            )
            return (kind, module.name if kind == 2 else "", node.lineno)

        return sorted(entries, key=key)

    def submodule(self, name: str) -> None:
        module = self.module(name)
        exported = module.exported()
        if exported is None:
            exported = [n for n in module.defined() if not n.startswith("_")]
        entries = []
        for item in exported:
            found = self.resolve(module, item)
            if found is None:
                raise Failure(
                    f"{name}.{item}: in __all__ but defined in no stub or module"
                )
            source, node = found
            if source.name != name and f"{source.name}.{item}" in self.documented:
                continue
            entries.append((item, source, node))
        self.emit(f"## {name} {{#{name}}}")
        self.emit()
        self.prose(module.docs.module, name)
        shared = [item for item in exported if item not in {e[0] for e in entries}]
        if shared:
            names = ", ".join(f"[`{item}`](#binbun.{item})" for item in shared)
            self.emit(f"Also here, as in `binbun`: {names}.")
            self.emit()
        own = [(n, m, s) for n, m, s in entries if m.name == name]
        others = [(n, m, s) for n, m, s in entries if m.name != name]
        self.render_items(own + others, name)

    def render(self) -> str:
        self.emit(front_matter("Python API", 10))
        self.emit(
            "The `binbun` package: `pip install binbun`, then `import binbun`. "
            "Generated from its type stubs and docstrings; the guide is [Python](@/docs/python.md)."
        )
        self.emit()
        self.package()
        for name in ("binbun.x86", "binbun.aarch64", "binbun.ir"):
            self.submodule(name)
        text = "\n".join(self.out)
        return re.sub(r"\n{3,}", "\n\n", text).rstrip("\n") + "\n"


