#!/usr/bin/env python3
"""Writes the website's generated pages from binbun's sources:

- site/content/docs/reference/python.md: the Python API, from the type
  stubs (python/binbun/*.pyi, or the module itself where there is none)
  and the docstrings (the modules' own, and the extension's from the
  `///` comments of crates/binbun-py/src);
- site/content/docs/reference/c.md: the C API, from the comments of
  the headers in crates/binbun-capi/include/binbun (core.h, disasm.h);
- site/content/docs/reference/cli.md: the command line, from
  `binbun --help` and each command's own usage (the binary in $BINBUN or
  --binbun, else `binbun` on PATH);
- site/snippets/quick_start.* and decompiler_quick_start.*: the landing
  page's code panels, the examples/*/quick_start.* and
  examples/*/decompiler_quick_start.* programs without their header
  comments.

    scripts/site/generate.py [--check] [--binbun PATH] [python] [c] [cli] [landing]

With no part named, every part. --check writes nothing and fails if a
file differs from what it would write. The same sources give the same
bytes.
"""

